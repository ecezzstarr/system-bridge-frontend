import {getBusinessDb} from '@/lib/client-business-store'
import {projectPublicWorldDomain,type WorldDomainRow} from '@/lib/weave-open-world-domains'

export const BURNING_RIVER_LOOP='flame-event-01' as const

/** Idempotent schema install for older databases; migration is also checked in. */
export async function ensureWeaveOpenWorldSchema(sql:any=getBusinessDb()){
  await sql`
    CREATE TABLE IF NOT EXISTS weave_open_world_domains (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      world_slot bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
      client_id uuid NOT NULL UNIQUE,
      file_number varchar(120) NOT NULL UNIQUE,
      tier varchar(20) NOT NULL DEFAULT 'unclassified'
        CHECK (tier IN ('standard','pro','premium','plus','unclassified')),
      collaboration_open boolean NOT NULL DEFAULT false,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    )
  `
  await sql`
    CREATE TABLE IF NOT EXISTS weave_open_world_connections (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      loop_key varchar(64) NOT NULL,
      domain_a uuid NOT NULL REFERENCES weave_open_world_domains(id),
      domain_b uuid NOT NULL REFERENCES weave_open_world_domains(id),
      requested_by uuid NOT NULL REFERENCES weave_open_world_domains(id),
      status varchar(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','accepted','declined')),
      request_note varchar(240) NOT NULL DEFAULT '',
      created_at timestamptz NOT NULL DEFAULT now(),
      responded_at timestamptz,
      CHECK (domain_a < domain_b),
      CHECK (requested_by=domain_a OR requested_by=domain_b),
      UNIQUE(loop_key,domain_a,domain_b)
    )
  `
  await sql`
    CREATE TABLE IF NOT EXISTS weave_open_world_projects (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      connection_id uuid NOT NULL REFERENCES weave_open_world_connections(id),
      created_by_domain uuid NOT NULL REFERENCES weave_open_world_domains(id),
      kind varchar(32) NOT NULL CHECK(kind IN (
        'shared_service','distribution','media','commerce','system_integration'
      )),
      title varchar(120) NOT NULL,
      status varchar(20) NOT NULL DEFAULT 'proposed' CHECK(status IN ('proposed','active')),
      created_at timestamptz NOT NULL DEFAULT now(),
      accepted_at timestamptz
    )
  `
  await sql`
    CREATE TABLE IF NOT EXISTS weave_open_world_project_contributions (
      project_id uuid NOT NULL REFERENCES weave_open_world_projects(id),
      domain_id uuid NOT NULL REFERENCES weave_open_world_domains(id),
      system_id uuid NOT NULL REFERENCES client_built_systems(id),
      created_at timestamptz NOT NULL DEFAULT now(),
      PRIMARY KEY(project_id,domain_id)
    )
  `
  await sql`CREATE INDEX IF NOT EXISTS idx_weave_open_world_projects_connection ON weave_open_world_projects(connection_id,status,created_at DESC)`
  await sql`CREATE INDEX IF NOT EXISTS idx_weave_open_world_contributions_domain ON weave_open_world_project_contributions(domain_id,created_at DESC)`
  await sql`CREATE INDEX IF NOT EXISTS idx_weave_open_world_domains_slot ON weave_open_world_domains(world_slot)`
  await sql`CREATE INDEX IF NOT EXISTS idx_weave_open_world_connections_a ON weave_open_world_connections(domain_a,status,created_at DESC)`
  await sql`CREATE INDEX IF NOT EXISTS idx_weave_open_world_connections_b ON weave_open_world_connections(domain_b,status,created_at DESC)`
}

/** A purchase activates exactly one permanent world slot, not one slot per visit. */
export async function provisionPurchasedWorldDomain(params:{
  sql:any;clientId:string;fileNumber:string;tier?:string|null
}){
  const {sql,clientId,fileNumber}=params
  await ensureWeaveOpenWorldSchema(sql)
  const tier=['standard','pro','premium','plus'].includes(String(params.tier))
    ?String(params.tier):'unclassified'
  // Ensure only a verified, active folder owner can occupy a position.
  const [domain]=await sql`
    INSERT INTO weave_open_world_domains(client_id,file_number,tier)
    SELECT f.client_id,f.file_number,${tier}
    FROM client_file_folders f
    JOIN users u ON u.id=f.client_id
    WHERE f.client_id=${clientId}::uuid
      AND f.file_number=${fileNumber}
      AND f.status='active' AND u.role='client' AND COALESCE(u.is_active,true)=true
    ON CONFLICT(file_number) DO UPDATE SET
      tier=CASE WHEN EXCLUDED.tier='unclassified' THEN weave_open_world_domains.tier
        ELSE EXCLUDED.tier END,
      updated_at=now()
    WHERE weave_open_world_domains.client_id=EXCLUDED.client_id
    RETURNING id,world_slot,tier
  `
  if(!domain)throw new Error('Verified File Folder ownership is required for the public world')
  return {domainId:String(domain.id),slot:Number(domain.world_slot),tier:String(domain.tier)}
}

/** Reconcile older real Client folders without creating fictional sales. */
export async function reconcileExistingWorldDomains(sql:any){
  await ensureWeaveOpenWorldSchema(sql)
  const result=await sql`
    INSERT INTO weave_open_world_domains(client_id,file_number)
    SELECT f.client_id,f.file_number
    FROM client_file_folders f
    JOIN users u ON u.id=f.client_id
    WHERE f.client_id IS NOT NULL AND f.status='active'
      AND u.role='client' AND COALESCE(u.is_active,true)=true
    ORDER BY f.created_at ASC,f.file_number ASC
    ON CONFLICT DO NOTHING
    RETURNING id
  `
  // Files bought in older versions may have their tier only in a confirmed sale.
  const [tables]=await sql`
    SELECT to_regclass('public.file_folder_purchases')::text AS purchases
  `
  if(tables?.purchases){
    await sql`
      UPDATE weave_open_world_domains d
      SET tier=confirmed.file_folder_tier,updated_at=now()
      FROM (
        SELECT DISTINCT ON(file_number)
          file_number,file_folder_tier
        FROM file_folder_purchases
        WHERE status='confirmed'
          AND file_folder_tier IN ('standard','pro','premium','plus')
          AND file_number IS NOT NULL
        ORDER BY file_number,confirmed_at DESC NULLS LAST,created_at DESC
      ) confirmed
      WHERE d.file_number=confirmed.file_number
        AND d.tier IS DISTINCT FROM confirmed.file_folder_tier
    `
  }
  // Employee Client File Folders are issued via approved company offers,
  // not retail purchase receipts. Their real Standard/Pro/Premium/Plus
  // entitlement must also determine their exterior world.
  const [staffTables]=await sql`
    SELECT to_regclass('public.company_client_staff_offers')::text AS offers
  `
  if(staffTables?.offers){
    await sql`
      UPDATE weave_open_world_domains d
      SET tier=o.folder_tier,updated_at=now()
      FROM company_client_staff_offers o
      WHERE o.client_id=d.client_id
        AND o.file_number=d.file_number
        AND o.status='approved'
        AND o.folder_tier IN ('standard','pro','premium','plus')
        AND d.tier IS DISTINCT FROM o.folder_tier
    `
  }
  return result.length
}

/** All Client construction details remain server-side; this returns safe counts. */
export async function getPublicBurningRiverWorld(sql:any,page=0){
  await ensureWeaveOpenWorldSchema(sql)
  const offset=Math.min(100000,Math.max(0,Math.trunc(page)))*48
  const rows=await sql`
    SELECT d.id,d.world_slot AS slot,d.tier,d.collaboration_open AS available_for_collaboration,
      s.public_slug,
      CASE WHEN s.enabled=true AND s.world_host_customer_market=true
        AND s.formation_status IN ('selling','ready_for_offer')
        AND EXISTS(
          SELECT 1 FROM client_built_systems cd
          WHERE cd.client_id=d.client_id AND cd.file_number=d.file_number
            AND cd.system_type='customer_door' AND cd.status='active'
        )
      THEN true ELSE false END AS open_door,
      CASE WHEN s.enabled=true AND s.world_host_customer_market=true
        AND s.formation_status IN ('selling','ready_for_offer')
        THEN s.name ELSE NULL END AS public_name,
      (SELECT count(*)::int FROM client_file_folder_builds b
        WHERE b.client_id=d.client_id AND b.file_number=d.file_number
          AND b.status='building') AS building_count,
      (SELECT count(*)::int FROM client_file_folder_builds b
        WHERE b.client_id=d.client_id AND b.file_number=d.file_number
          AND b.status='complete') AS completed_count,
      (SELECT count(*)::int FROM client_built_systems b
        WHERE b.client_id=d.client_id AND b.file_number=d.file_number
          AND b.status='active') AS operating_count,
      (SELECT count(*)::int FROM client_store_items i
        WHERE i.store_id=s.id AND i.enabled=true) AS published_offers,
      (SELECT count(*)::int FROM weave_open_world_connections c
        WHERE c.loop_key=${BURNING_RIVER_LOOP}
          AND c.status='accepted' AND (c.domain_a=d.id OR c.domain_b=d.id)) AS accepted_connections,
      (SELECT count(*)::int FROM weave_open_world_projects p
        JOIN weave_open_world_connections c ON c.id=p.connection_id
        WHERE c.loop_key=${BURNING_RIVER_LOOP}
          AND c.status='accepted' AND p.status='active'
          AND (c.domain_a=d.id OR c.domain_b=d.id)
          AND (SELECT count(DISTINCT pc.domain_id) FROM weave_open_world_project_contributions pc
            JOIN weave_open_world_domains contributor ON contributor.id=pc.domain_id
            JOIN client_built_systems active_system
              ON active_system.id=pc.system_id
              AND active_system.client_id=contributor.client_id
              AND active_system.file_number=contributor.file_number
              AND active_system.status='active'
            WHERE pc.project_id=p.id)=2) AS linked_projects,
      (SELECT max(CASE WHEN b.completes_at>b.started_at THEN
         GREATEST(0,LEAST(100,
           EXTRACT(EPOCH FROM (now()-b.started_at))/
           NULLIF(EXTRACT(EPOCH FROM (b.completes_at-b.started_at)),0)*100))
        ELSE 0 END)
       FROM client_file_folder_builds b
       WHERE b.client_id=d.client_id AND b.file_number=d.file_number
         AND b.status='building') AS forming_progress
    FROM weave_open_world_domains d
    JOIN client_file_folders f ON f.client_id=d.client_id AND f.file_number=d.file_number
    JOIN users owner ON owner.id=d.client_id AND owner.role='client' AND COALESCE(owner.is_active,true)=true
    LEFT JOIN client_business_stores s ON s.client_id=d.client_id AND s.file_number=d.file_number
    WHERE f.status='active'
    ORDER BY d.world_slot ASC
    LIMIT 48 OFFSET ${offset}
  `
  const links=await sql`
    SELECT c.domain_a,c.domain_b
    FROM weave_open_world_connections c
    JOIN weave_open_world_domains a ON a.id=c.domain_a
    JOIN weave_open_world_domains b ON b.id=c.domain_b
    JOIN client_file_folders fa ON fa.client_id=a.client_id AND fa.file_number=a.file_number
    JOIN client_file_folders fb ON fb.client_id=b.client_id AND fb.file_number=b.file_number
    JOIN users ua ON ua.id=a.client_id AND ua.role='client' AND COALESCE(ua.is_active,true)=true
    JOIN users ub ON ub.id=b.client_id AND ub.role='client' AND COALESCE(ub.is_active,true)=true
    WHERE c.loop_key=${BURNING_RIVER_LOOP} AND c.status='accepted'
      AND fa.status='active' AND fb.status='active'
    ORDER BY c.responded_at DESC
    LIMIT 120
  `
  const domains=rows.map((row:any)=>projectPublicWorldDomain({
    id:String(row.id),slot:row.slot,tier:row.tier,public_slug:row.public_slug,
    public_name:row.public_name,open_door:row.open_door,
    building_count:row.building_count,completed_count:row.completed_count,
    operating_count:row.operating_count,published_offers:row.published_offers,
    accepted_connections:row.accepted_connections,linked_projects:row.linked_projects,
    forming_progress:row.forming_progress,
    available_for_collaboration:row.available_for_collaboration,
  } as WorldDomainRow))
  const included=new Set(domains.map((d:any)=>d.domainId))
  return {
    domains,
    links:links.filter((link:any)=>included.has(String(link.domain_a))&&included.has(String(link.domain_b)))
      .map((link:any)=>({from:String(link.domain_a),to:String(link.domain_b)})),
    page,
    hasMore:rows.length===48,
  }
}
