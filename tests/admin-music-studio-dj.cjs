const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const model=read('lib/admin-music-studio.ts')
const projects=read('app/api/admin/music-studio/route.ts')
const media=read('app/api/admin/music-studio/media/route.ts')
const publish=read('app/api/admin/music-studio/publish/route.ts')
const engine=read('lib/music-loop-engine.ts')
const compositor=read('app/(app)/admin/music-studio/page.tsx')
const dj=read('app/(app)/admin/dj-workshop/page.tsx')
const realEditor=read('components/music-workshop/music-conversation-editor.tsx')
const publicMedia=read('app/api/media/[...path]/route.ts')
const broadcast=read('app/api/dj/broadcast/route.ts')
const djPlaylist=read('app/api/admin/dj/playlists/route.ts')

assert.ok(model.includes("user?.role==='admin'"),'Only server-verified Administrators can operate institution-wide music')
assert.ok(model.includes('weave_admin_music_projects')&&model.includes('weave_admin_music_assets'),'Institutional compositions and audio assets have separate storage')
assert.ok(model.includes('weave_admin_music_releases'),'Published songs preserve a DJ release trace')
assert.ok(model.includes('MUSIC_SONG_MAX_SECONDS=160'),'Song render is bounded to the current 30 MB DJ WAV capacity')
assert.ok(model.includes('arrangement.tracks.filter(t=>!t.muted&&t.level>0).length<2'),'Advanced song sections require two audible tracks')
for(const file of [projects,media,publish]){
 assert.ok(file.includes('requireMusicAdministrator(request)'),'Administration auth is checked on all music storage, read and publish routes')
}
assert.ok(projects.includes('cleanMusicArrangement'),'Admin project compositions are validated before saving')
assert.ok(projects.includes('weave_admin_music_assets WHERE id=ANY'),'Projects cannot reference arbitrary unknown audio asset IDs')
assert.ok(media.includes('weave-private/admin-music/'),'Recorded Admin stems are stored outside public media')
assert.ok(media.includes('MAX=16*1024*1024')&&media.includes('512*1024*1024'),'Institutional sound upload/storage caps are enforced')
assert.ok(media.includes('Cache-Control')&&media.includes('private, no-store'),'Private source recordings cannot be cached as public DJ audio')
assert.ok(publicMedia.includes("objectName.startsWith('weave-private/admin-music/')"),'Generic Weave media gateway denies private Admin stems')
assert.ok(engine.includes('exportAdvancedSongWav')&&engine.includes('new OfflineAudioContext'),'Advanced song is rendered using real audio, not simulated playback')
assert.ok(engine.includes('renderBeat(context,part.arrangement,buffers,beat,beginning+beat*unit)'),'All song sections render on one uninterrupted beat timeline')
assert.ok(publish.includes('parseWav(bytes)'),'DJ publishing verifies actual PCM WAV audio')
assert.ok(publish.includes('Math.abs(decodedSeconds-intendedSeconds)>.12'),'WAV duration must match the saved song arrangement')
assert.ok(publish.includes('await ensureDjSchema()')&&publish.includes('INSERT INTO dj_tracks('),'Released songs enter the existing DJ track library')
assert.ok(publish.includes('INSERT INTO weave_admin_music_releases'),'DJ track publication is linked to saved production metadata')
assert.ok(publish.includes("await client.query('BEGIN')")&&publish.includes("await client.query('COMMIT')"),'DJ publication and release records use a single transaction')
assert.ok(!publish.includes('UPDATE dj_broadcast_state'),'Publishing does not start an unwanted global broadcast')
assert.ok(compositor.includes('data-admin-song-arrangement="multi-section"'),'Administration has a real advanced song arranger')
assert.ok(compositor.includes('exportAdvancedSongWav(')&&compositor.includes('Render and listen'),'Songs can be previewed before being published')
assert.ok(compositor.includes('Publish to DJ Library')&&compositor.includes("'/api/admin/music-studio/publish'"),'Composition is explicitly handed off to DJ')
assert.ok(realEditor.includes("mode==='administration'")&&realEditor.includes("'/api/admin/music-studio/media'"),'The existing real editor is shared but isolates staff from Client sound assets')
assert.ok(dj.includes('href="/admin/music-studio"'),'Existing DJ Workshop exposes Music Studio entrance')
assert.ok(broadcast.includes('resolveDjBroadcastState()'),'Public users continue using synchronized DJ playback')
assert.ok(djPlaylist.includes('FROM dj_tracks'),'New WEAVE songs are selectable by the existing DJ playlist engine')
console.log('Administration Music Studio: access, audio, songs, DJ publication and privacy checks passed.')
