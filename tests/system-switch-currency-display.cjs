const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8')
const currency=read('lib/flame-coin.ts')
const ledger=read('app/(app)/ledger/page.tsx')
const wallet=read('app/api/wallet/balance/route.ts')
const pricing=read('lib/world/constants.ts')
const sales=read('lib/weave-flame-coin-sales.ts')
const doc=read('docs/system-switch-currency-roadmap.md')
assert(currency.includes("SYSTEM_SWITCH_NAME = 'System Switch'"),'System Switch must be the public name')
assert(currency.includes('FLAME_COIN_NAME = SYSTEM_SWITCH_NAME'),'Older helper imports remain compatible')
assert(currency.includes("FLAME_COIN_CODE = 'FLAME_COIN'"),'Historical accounting code must not be renamed')
assert(currency.includes('export function displayCurrencyName'),'Historical labels must normalize only for display')
assert(currency.includes("'FLAME_COIN', 'FLAMECOIN', 'SYSTEM_SWITCH'"),'Old and new labels must display consistently')
assert(ledger.includes('displayCurrencyName(entry.currency)'),'Ledger must display historical entries under the new name')
assert(ledger.includes('currency="System Switch"'),'Balance display must use System Switch')
assert(wallet.includes("currency: 'System Switch'"),'Public wallet currency label must be updated')
assert(wallet.includes("legacyCurrencyCode: 'FLAME_COIN'"),'Legacy currency identifier remains explicit')
assert(pricing.includes('FILE_FOLDER_PREMIUM_PRICE_FLAME_COIN'),'Financial pricing identifiers remain unchanged')
assert(sales.includes("'Flame Coin','paid'"),'Raw financial persistence still uses the legacy code')
assert(sales.includes('Funded customer System Switch purchase'),'Customer narration reflects new name')
assert(doc.includes('not the issuance or registration of a cryptocurrency'),'No on-chain claim without future authorization')
console.log('System Switch naming and historical ledger compatibility: passed')
