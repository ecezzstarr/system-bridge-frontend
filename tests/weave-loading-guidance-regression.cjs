const fs=require('node:fs')
const path=require('node:path')
const vm=require('node:vm')
const ts=require('typescript')
const assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const source=read('lib/weave-loading-guidance.ts')
const translated=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText
const moduleExports={}
vm.runInNewContext(translated,{exports:moduleExports},{filename:'lib/weave-loading-guidance.ts'})
const {trainingBriefsForRole,agentOperatingGuideForPath,transitTrainingForPath,lyricLinesForBrief}=moduleExports
for(const role of ['visitor','agent','bridger','client','admin']){
  const cards=trainingBriefsForRole(role)
  assert.equal(cards.length,3,role+' needs three training cards')
  assert.ok(cards.every(card=>card.title&&card.body&&card.movement),'All messages teach something usable')
  for(const brief of cards){
    const lines=lyricLinesForBrief(brief)
    assert.equal(lines.length,5,'The lyric introduces the destination, teaches three beats and ends with the movement')
    assert.equal(lines[0],brief.title)
    assert.equal(lines.at(-1),brief.movement)
    assert.equal(lines.slice(1,-1).join(' '),brief.body,'The lyric preserves every instructional word')
  }
}
assert.ok(trainingBriefsForRole('agent')[0].title.includes('Stability'))
assert.ok(trainingBriefsForRole('agent')[1].body.includes('1.5 Flame Coin'))
assert.ok(trainingBriefsForRole('bridger')[1].body.includes('unverified'))
assert.ok(trainingBriefsForRole('client')[1].title.includes('real time'))
assert.ok(trainingBriefsForRole('admin')[1].body.includes('verification')||trainingBriefsForRole('admin')[1].body.includes('confirmed'))
assert.ok(trainingBriefsForRole('visitor').some(item=>item.body.includes('System Switch')))
assert.equal(agentOperatingGuideForPath('/video-ad-studio').nextHref,'/agent/creative')
assert.equal(agentOperatingGuideForPath('/weave/carrier/food').nextHref,'/weave/carrier/food')
assert.equal(agentOperatingGuideForPath('/agility').nextHref,'/agent/work')
assert.equal(agentOperatingGuideForPath('/agent/commissions').nextHref,'/agent/commissions')
assert.equal(agentOperatingGuideForPath('/event').nextHref,'/agent/work')
assert.ok(transitTrainingForPath('agent','/agility')?.body.includes('product'))
assert.equal(transitTrainingForPath('visitor','/'),null)
assert.ok(transitTrainingForPath('agent','/manager/dashboard')?.title.includes('Distribution Manager'),'Agent loader accurately explains Distribution Manager')
assert.ok(transitTrainingForPath('bridger','/manager/dashboard')?.title.includes('Distribution Manager'),'Bridger loader accurately explains Distribution Manager')
assert.ok(read('components/world/weave-environment-transit.tsx').includes('body:`${destinationEnvironment.purpose} ${guidance.body}`'),'Known destinations include the verified environment purpose before role-specific detail')
const transit=read('components/world/weave-environment-transit.tsx')
assert.ok(transit.includes('trainingBriefsForRole'),'Loader uses real training copy')
assert.ok(transit.includes("role==='agent'"),'Authenticated Agent receives the right content')
assert.ok(transit.includes('transitTrainingForPath(role,destinationPath)'), 'Travel brief understands destination')
assert.ok(transit.includes('const LOADING_CARD_HOLD_MS=5*BOOT_LYRIC_STEP_MS')&&transit.includes('const TRANSIT_FORMATION_MS=5*TRANSIT_LYRIC_STEP_MS'),'Both boot and internal entrances remain visible for their complete timed lyrics')
assert.ok(transit.includes('waitForEnvironmentReadiness(mode,configRef.current,controller.signal)'), 'Readiness still decides when the world reveals')
assert.ok(transit.includes('data-weave-loader-lyrics="timed-instruction"')&&transit.includes('weave-loader-lyric-current'),'Lyric content is active inside the actual loader')
const guide=read('components/agent/agent-smart-guide.tsx')
const app=read('app/(app)/layout.tsx')
assert.ok(guide.includes('data-weave-guide-trigger="bubble"')&&guide.includes('h-12 w-12'),'Guide stays as a compact closed bubble')
assert.ok(!guide.includes('setOpen(true)')&&guide.includes('if(input)setOpen(false)'),'Guide does not auto-open or obstruct signatures')
assert.ok(app.includes('<AgentSmartGuide userId={user.id}/>')&&app.includes('<BridgerSmartGuide userId={user.id}/>'),'Both roles keep the Guide')
assert.equal(agentOperatingGuideForPath('/manager/dashboard').nextHref,'/manager/dashboard')
const fileFolder=read('components/system-switch/file-folder-environment-loader.tsx')
assert.ok(fileFolder.includes('Preview before building')&&fileFolder.includes('Operate when active'),'File Folder loader teaches truthful operation')
console.log('Role-specific loading training, contextual destination guidance, and on-page continuation passed')
