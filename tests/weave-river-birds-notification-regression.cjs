const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const bell = fs.readFileSync(path.join(root, 'components/notification-bell.tsx'), 'utf8')
const header = fs.readFileSync(path.join(root, 'components/app-header.tsx'), 'utf8')
const audioPath = path.join(root, 'public/sounds/weave-river-birds.mp3')
const recording = fs.readFileSync(audioPath)

assert.ok(recording.length > 3000 && recording.length < 2_000_000, 'approved recording should be shipped as a finite local audio file')
assert.ok(recording.subarray(0,3).toString() === 'ID3' || recording[0] === 0xff, 'recording should be an MP3')
assert.ok(bell.includes("new Audio('/sounds/weave-river-birds.mp3')"), 'notification sound must use the approved local recording')
assert.ok(!bell.includes('data:audio/wav;base64,'), 'legacy synthetic audio must be removed')
assert.ok(bell.includes('data-weave-notification-sound="river-birds"'), 'bell must expose River & Birds settings')
assert.ok(bell.includes('audio.currentTime = 0') && bell.includes('await audio.play()'), 'new alert must restart the recording')
assert.ok(bell.includes('soundBlocked') && bell.includes('Tap Test to enable audio on this phone'), 'mobile autoplay restrictions must be handled visibly')
assert.ok(bell.includes("localStorage.setItem('weave_notification_sound'"), 'sound preferences must be persistent on the current device')
assert.ok(bell.includes("freshOnes.length > 0") && bell.includes('void playRiverAlert()'), 'new unread notifications must trigger the audio')
assert.ok(bell.includes('visiblePoll(fetchNotifications, 5000)'), 'foreground notification polling must remain intact')
assert.ok(bell.includes('markAllAsRead') && bell.includes('markAsRead'), 'mark-read operation must remain intact')
assert.ok(header.includes('<NotificationBell') && header.includes('AppHeader'), 'all authenticated role headers retain the notification bell')

console.log('Approved WEAVE River & Birds sound and notification integration checks passed')
