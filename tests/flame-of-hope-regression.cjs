// Regression checks for Flame of Hope promotional reward boundaries.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const route = fs.readFileSync('app/api/bridger/flame-of-hope/route.ts','utf8')
const page = fs.readFileSync('app/(app)/bridger/flame-of-hope/page.tsx','utf8')
const migration = fs.readFileSync('migrations/20261113_flame_of_hope_claims.sql','utf8')
const event = fs.readFileSync('app/(app)/event/page.tsx','utf8')

assert.match(route, /randomInt\(1,9\)/, 'Reward must be uniform 1 to 8')
assert.match(route, /user\.role !== 'bridger'/, 'Only Bridgers can claim')
assert.match(route, /getFlameEvent\(\)/, 'Claims must respect live event')
assert.match(route, /event\.effectiveStatus === 'active'/, 'Claims require active event')
assert.match(route, /WEAVE_FLAME_OF_HOPE_TREASURY_USER_ID/, 'Rewards must be funded')
assert.match(route, /FOR UPDATE OF w/, 'Treasury must be locked before transferring')
assert.match(route, /ON CONFLICT\(bridger_id,event_key,claim_day\) DO NOTHING/, 'Retries must be idempotent')
assert.match(route, /recoverSupportAdvanceFromEarning/, 'Outstanding authorized work advances must be handled')
assert.doesNotMatch(route, /prospect_response/, 'Unverified replies must not earn financial rewards')
assert.match(route, /referral_bonus_awards/, 'Verified referral activity qualifies')
assert.match(route, /bridger_commission/, 'Verified File Folder sales qualify')
assert.match(migration, /UNIQUE \(bridger_id, event_key, claim_day\)/, 'Only one claim per day')
assert.match(page, /1–8 System Switch/, 'Player sees the exact prize range')
assert.match(page, /no payment required/i, 'Free claim is not paid gambling')
assert.match(event, /\/bridger\/flame-of-hope/, 'Reward appears on event ground')
console.log('Flame of Hope static regression checks passed')
