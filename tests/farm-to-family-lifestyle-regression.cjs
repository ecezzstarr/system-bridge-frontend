const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const states=read('lib/food-bridge-states.ts')
const model=read('lib/food-bridge.ts')
const access=read('lib/food-bridge-access.ts')
const offers=read('app/api/flame/food/route.ts')
const farm=read('app/api/flame/food/farmer/route.ts')
const orders=read('app/api/flame/food/orders/route.ts')
const administration=read('app/api/admin/flame-food/route.ts')
const lifestyle=read('app/(app)/weave/lifestyles/page.tsx')
const lifestylePage=read('app/(app)/weave/lifestyles/food/page.tsx')
const ui=read('components/flame-food/farmer-household-food-bridge.tsx')
const homepage=read('app/page.tsx')

const names=[...states.matchAll(/'([^']+)'/g)].map(x=>x[1])
const geographicNames=names.slice(0,names.indexOf('kg'))
assert.equal(geographicNames.length,37,'36 states plus FCT only')
assert.equal(new Set(geographicNames).size,37,'No duplicate state names')
assert.ok(geographicNames.includes('Kano')&&geographicNames.includes('Lagos')&&geographicNames.includes('Benue'),'Farm-to-Lagos routes are available')

assert.ok(access.includes('getAuthUser(request)')&&access.includes('getLifestyleAccess(user.id)'),'All trades require real WEAVE sessions and Lifestyle standing')
assert.ok(access.includes("['agent','bridger'].includes(user.role)")&&access.includes('!access.active'),'No public or Legion trade bypass')
assert.ok(offers.includes("user.role!=='agent'")&&offers.includes('agent_id'), 'Farmer selling belongs to Agent accounts')
assert.ok(offers.includes("f.status='approved'")&&offers.includes("l.status='active'"),'Only approved real stock appears in catalogue')
assert.ok(orders.includes('buyer_user_id=$1::uuid')&&orders.includes('buyer_user_id=$2::uuid'),'Orders and mutations are bound to the current account')
assert.ok(orders.includes('available_quantity=l.available_quantity-$1::numeric'),'Quantity reservation is atomic')
assert.ok(orders.includes('l.available_quantity >= $1::numeric'),'Overstock promises are rejected')
assert.ok(orders.includes("f.agent_id<>$3::uuid"),'A farmer cannot place a buyer order on their own farm')
assert.ok(model.includes("status='expired'")&&model.includes('RETURNING listing_id,quantity'),'Unanswered requests release their reserved stock')
assert.ok(orders.includes("['requested','farmer_confirmed','quoted','accepted']")&&orders.includes('available_quantity=LEAST(original_quantity'), 'Buyer cancellation returns stock once')
assert.ok(farm.includes("status='rejected'")&&farm.includes('available_quantity=LEAST(original_quantity'),'Farmer declines restore stock')
assert.ok(farm.includes("status='quoted'")&&farm.includes("status='farmer_confirmed'"),'A farmer must confirm supply before quoting transportation')
assert.ok(orders.includes("order.status!=='quoted'"),'A buyer can accept only a completed quote')
assert.ok(orders.includes("status='delivered'"),'A buyer independently confirms delivery')
assert.ok(administration.includes("user?.role === 'admin'")&&administration.includes("status='pending'"),'Administration independently verifies farmers')
assert.ok(administration.includes('contact_private')&&!offers.includes('contact_private')&&!ui.includes('contact_private'),'Farmer contact is not public catalog data')
assert.ok(model.includes('buyer_phone_private')&&farm.includes('share_buyer_contact'),'Buyer contact requires explicit opt in')
assert.ok(lifestyle.includes('FARM TO FAMILY')&&lifestyle.includes("'/weave/lifestyles/food'"),'The exchange is an actual Lifestyle surface')
assert.ok(lifestylePage.includes('FarmerHouseholdFoodBridge')&&ui.includes('data-lifestyle-food'),'Lifestyle route renders the trading environment')
assert.ok(homepage.includes('data-home-farm-to-family')&&homepage.includes('href="/register"'),'A visitor can enter through WEAVE registration')
assert.ok(!ui.includes('localStorage.setItem(\'weave_food_farmer_key\''),'No separate farmer access key is required')
console.log('Farm-to-Family Lifestyle source-level regression checks passed')
