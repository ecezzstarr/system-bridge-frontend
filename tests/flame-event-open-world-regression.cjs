assert.match(scene, /<svg[\s\S]*Burning River/)
assert.match(scene, /id="river"/)
assert.match(scene, /id="fire"/)
assert.match(scene, /prefers-reduced-motion/)
assert.match(world, /burning-river-world\.svg/)
assert.match(world, /data-flame-event-open-world="burning-river"/)
assert.match(world, /data-flame-event-crossing="system-switch-customer-doors"/)
