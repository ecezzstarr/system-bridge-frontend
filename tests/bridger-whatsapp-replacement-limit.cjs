const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = p => fs.readFileSync(path.join(__dirname, '..', p), 'utf8')

const report = read('app/api/bridger/prospects/[outreachId]/report-invalid/route.ts')
const quota = read('lib/bridger-prospect-replacements.ts')
const mine = read('app/api/bridger/prospects/route.ts')
const ui = read('app/(app)/weave/market/prospects/page.tsx')

assert.match(quota, /DAILY_WHATSAPP_REPLACEMENT_LIMIT = 10/, 'Ten replacements per Bridger per day')
assert.match(quota, /actor_id = \$1::uuid/, 'Quota is scoped to the logged-in Bridger')
assert.match(quota, /action = 'whatsapp_replacement_issued'/, 'Quota counts successful issuances rather than taps')
assert.match(quota, /Africa\/Lagos/, 'Quota resets with the Nigeria calendar day')

assert.match(report, /authUser\.role !== 'bridger'/, 'Reporting is restricted to Bridgers')
assert.match(report, /SELECT id FROM users WHERE id=\$1::uuid AND role='bridger' FOR UPDATE/, 'Concurrent reports serialize on the Bridger')
assert.ok(report.indexOf('const actorLock') < report.indexOf('getDailyWhatsAppReplacementCount(client'), 'Lock acquired before count')
assert.match(report, /remainingToday > 0 \? await client\.query/, 'No contact assignment after quota exhaustion')
assert.match(report, /LIMIT 1\s+FOR UPDATE OF m SKIP LOCKED/, 'At most one unused replacement per report')
assert.match(report, /m\.package_id IS NULL/, 'Purchased package contacts are excluded')
assert.match(report, /NOT EXISTS \(SELECT 1 FROM market_prospect_outreach/, 'Already assigned contacts are excluded')
assert.match(report, /NOT EXISTS \(SELECT 1 FROM bridger_daily_prospect_claims/, 'Daily claimed contacts are excluded')
assert.match(report, /outreach\.status === 'invalid_number'/, 'Repeated invalid reports are rejected')
assert.match(report, /reported_invalid_whatsapp/, 'Every invalid report is audited')
assert.match(report, /'whatsapp_replacement_issued'/, 'Actual replacements are counted through audit entries')
assert.match(report, /replacementsRemaining: Math\.max\(0, remainingToday - newProspects\.length\)/, 'API returns remaining daily quota')
assert.match(report, /remainingToday === 0/, 'Reports after quota exhaustion do not issue a candidate')
assert.match(report, /\['pending', 'sent'\]/, 'Reports can follow a failed first WhatsApp send')

assert.match(mine, /getDailyWhatsAppReplacementCount\(getPool\(\), authUser\.id\)/, 'My Prospects reads server-side daily usage')
assert.match(mine, /replacementQuota:/, 'My Prospects API returns quota')
assert.match(ui, /data-whatsapp-replacement-quota="daily"/, 'My Prospects displays daily usage')
assert.match(ui, /replacementQuota\.used/, 'Daily issuance count is visible')
assert.ok((ui.match(/Not on WhatsApp\?/g) || []).length >= 2, 'Pending and sent prospect cards can report invalid WhatsApp numbers')

console.log('Bridger WhatsApp replacement daily cap checks passed')
