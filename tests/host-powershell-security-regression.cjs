const fs=require('node:fs')
const assert=require('node:assert/strict')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const pwsh=read('selfhost/host-powershell.ps1')
const worker=read('app/api/system/host-powershell/route.ts')
const admin=read('app/api/admin/host-powershell/route.ts')
const lib=read('lib/weave-host-powershell.ts')
const ui=read('components/admin/host-powershell-status.tsx')
const infrastructure=read('app/(app)/admin/infrastructure/page.tsx')
const login=read('app/api/auth/login/route.ts')
const auth=read('lib/auth-api.ts')
const next=read('next.config.mjs')
const nextAuth=read('lib/auth.ts')
const release=read('app/api/admin/release-workshop/route.ts')
const hostUnit=read('selfhost/weave-host-powershell.service')

assert.match(pwsh,/127\.0\.0\.1:3000\/api\/system\/host-powershell/,'PowerShell reports only over local loopback')
assert.match(pwsh,/docker inspect --format/,'Host reporter inspects fixed container status')
assert.match(pwsh,/function Snapshot/,'Snapshot produced by safe fixed operations')
assert.doesNotMatch(pwsh,/Invoke-Expression|Invoke-Command|ScriptBlock::Create|DownloadString|FromBase64String/,'No arbitrary shell commands or remote execution')
assert.match(hostUnit,/NoNewPrivileges=true/,'Host systemd restrictions enabled')
assert.match(hostUnit,/EnvironmentFile=\/etc\/weave\/host-powershell.env/,'Secrets are host-only')
assert.match(worker,/timingSafeEqual/,'Token checked in constant time')
assert.match(worker,/WEAVE_HOST_CONTROL_TOKEN/,'Dedicated host token required')
assert.doesNotMatch(worker,/getAuthUser\(|exec\(|spawn\(/,'No raw shell calls in website host API')
assert.match(admin,/requireWorkshopAuthorization/,'Only verified active platform Administration can inspect')
assert.match(lib,/filterHostSnapshot/,'Telemetry values are allowlisted')
assert.match(lib,/SELECT worker_key,last_seen_at,snapshot/,'Read access is snapshot-only')
assert.match(ui,/HostPowerShellStatus/,'Administration receives host view')
assert.match(infrastructure,/HostPowerShellStatus token=\{token\}/,'Host view integrated in existing Administration infrastructure')
assert.match(release,/requestReleaseJob/,'Deploy and rollback continue through existing release queue')
assert.doesNotMatch(login,/PLATFORM_ADMIN_FALLBACK_PASSWORD|PLATFORM_ADMIN|token_\$\{user.id\}_\$\{Date.now\(\)\}/,'Legacy privileged credentials and timestamp tokens removed')
assert.match(login,/randomBytes\(32\)/,'API login uses secure random 256-bit token')
assert.match(auth,/WHERE id = \$\{sessionUser.id\}::uuid AND is_active=true/,'NextAuth cookies revalidate enabled account')
assert.match(auth,/WHERE id = \$\{userId\}::uuid AND is_active=true/,'Bearer sessions revalidate enabled account')
assert.doesNotMatch(nextAuth,/your-secret-key-change-in-production/,'No default NextAuth signing secret')
assert.match(next,/ignoreBuildErrors: false/,'Build rejects TypeScript errors')
console.log('PASS: self-host PowerShell confinement, Administration authority and authentication hardening')
