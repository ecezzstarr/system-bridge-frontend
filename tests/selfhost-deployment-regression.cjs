const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=file=>fs.readFileSync(path.join(root,file),'utf8')

const compose=read('docker-compose.selfhost.yml')
const deploy=read('selfhost/deploy-production.sh')
const workflow=read('.github/workflows/weave-selfhost-deploy.yml')
const records=read('lib/weave-deployment-records.ts')
const recordApi=read('app/api/system/deployment-record/route.ts')
const infrastructure=read('lib/weave-infrastructure.ts')
const infrastructureApi=read('app/api/admin/infrastructure/route.ts')
const infrastructurePage=read('app/(app)/admin/infrastructure/page.tsx')
const health=read('app/api/health/route.ts')

assert.ok(compose.includes('WEAVE_RELEASE_SHA: ${WEAVE_RELEASE_SHA:-selfhost}'),'Self-host container receives exact release identity')
assert.ok(compose.includes('image: weave-release:${WEAVE_RELEASE_SHA:-selfhost}'),'Releases retain exact source SHA image tags for rollback')
assert.ok(compose.includes('127.0.0.1:3000:3000'),'WEAVE application remains private behind the edge')
assert.ok(compose.includes('"80:80"')&&compose.includes('"443:443"'),'Caddy owns the public HTTP/HTTPS edge')
assert.ok(deploy.includes('WEAVE_DEPLOY_TARGET_SHA'),'Deploy script accepts only the SHA verified by Production Check')
assert.ok(deploy.includes('if [[ "$REQUESTED_SHA" != "$ORIGIN_MAIN_SHA" ]]'),'Superseded verified releases cannot deploy over newer canonical main')
assert.ok(deploy.includes('build --pull weave')&&deploy.includes('up -d --remove-orphans'),'Self-host deployment rebuilds and restarts the canonical Compose application')
assert.ok(deploy.includes('wait_for_health http://127.0.0.1:3000/api/health'),'Deployment verifies local WEAVE health')
assert.ok(deploy.includes('https://${DOMAIN}/api/health'),'Deployment verifies the public WEAVE domain')
assert.ok(deploy.includes('rollback_started')&&deploy.includes('rolled_back'),'Failed releases carry an automatic rollback movement')
assert.ok(workflow.includes('workflow_dispatch:')&&!workflow.includes('workflow_run:'),'Production requires explicit Administration or recovery authorization instead of auto-deploy')
assert.ok(workflow.includes('runs-on: [self-hosted, linux]'),'Production executes on the WEAVE server runner, not Google Cloud')
assert.ok(workflow.includes('inputs.release_sha')&&workflow.includes('production-check.yml/runs'),'Manual recovery requires an exact main SHA and a successful Production Check')
assert.ok(records.includes('weave_deployment_records'),'WEAVE persists institutional deployment records')
assert.ok(records.includes('flame_system_records'),'Flame preserves runtime and release movement')
assert.ok(records.includes('eight_scroll')&&records.includes("'Sovereign'"),'Sovereign Scroll preserves deployment authority')
assert.ok(records.includes('recordSystemEvent'),'Deployment movement also enters the system event record')
assert.ok(recordApi.includes('WEAVE_DEPLOY_RECORD_TOKEN'),'Server-side deployment record writes require dedicated authority')
assert.ok(infrastructure.includes("deployment_target VARCHAR(40) NOT NULL DEFAULT 'selfhost'"),'Infrastructure defaults to self-host production')
assert.ok(infrastructure.includes('WEAVE Self-Host Runtime'),'Infrastructure registry identifies the new server runtime')
assert.ok(infrastructure.includes('Google runtime retired; WEAVE self-host is production authority'),'Legacy Google runtime rows are retired explicitly')
assert.ok(infrastructureApi.includes("mode:'selfhost'")&&infrastructureApi.includes("edge:'caddy'")&&infrastructureApi.includes("application:'docker-compose'"),'Administration reads the real self-host runtime')
assert.ok(infrastructureApi.includes('Cloud deployment actions are retired.'),'Administration cannot invoke old Cloud deployment actions')
assert.ok(!infrastructurePage.includes('Google Cloud Runtime')&&!infrastructurePage.includes('Deploy Preview')&&!infrastructurePage.includes('Promote Candidate'),'Administration UI exposes no Google production controls')
assert.ok(infrastructurePage.includes('Sovereign + Flame Record'),'Infrastructure Workshop exposes the deployment record')
assert.ok(health.includes('WEAVE_RELEASE_SHA'),'Health endpoint exposes release identity for deployment verification')

console.log('PASS: verified main deploys only through WEAVE self-host; Sovereign and Flame preserve deployment and rollback history')
