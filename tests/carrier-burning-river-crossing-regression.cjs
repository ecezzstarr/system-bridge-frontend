const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const read=name=>fs.readFileSync(path.join(__dirname,'..',name),'utf8')
const carrier=read('app/carrier/food/[code]/page.tsx')
const flamePage=read('app/flame-event/page.tsx')
const publicFlame=read('components/events/flame-event-public-mobile.tsx')
const world=read('components/events/flame-event-open-world.tsx')

assert.ok(carrier.includes('data-carrier-flame-event-entrance'),'Agent food door presents Flame Event entrance')
assert.ok(carrier.includes('/flame-event?carrier='),'Arrival retains Agent source code')
assert.ok(carrier.includes('<AgentFarmCarrierPublic referralCode={code}/>')&&carrier.includes('<AgentFoodCarrierPublic referralCode={code}/>')&&carrier.includes('<AgentCakeCarrierPublic referralCode={code}/>'),'Guest ordering remains on Carrier Door')
assert.ok(flamePage.includes('carrierCode')&&flamePage.includes('^[a-zA-Z0-9-]{1,40}$'),'Public crossing validates return code without granting access')
assert.ok(publicFlame.includes('data-flame-event-carrier-arrival')&&publicFlame.includes('data-flame-event-return-carrier'),'Flame Event offers return to originating Agent')
assert.ok(publicFlame.includes('role="visitor"'),'Arrival remains a visitor, never authenticated staff')
assert.ok(world.includes('data-flame-event-open-world="burning-river"')&&world.includes('FlameEventMobileScene'),'Visitor enters the existing live mobile Burning River')
console.log('Carrier Door → Flame Event → Carrier Door source regression passed')
