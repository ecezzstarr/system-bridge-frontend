const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const vm=require('node:vm')
const ts=require('typescript')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const source=read('lib/weave-loading-guidance.ts')
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText
const moduleExports={}
vm.runInNewContext(compiled,{exports:moduleExports})
const {roleOperatingGuideForPath,transitDirectionForPath,trainingBriefsForRole}=moduleExports

assert.equal(roleOperatingGuideForPath('agent','/video-ad-studio').nextHref,'/agent/creative')
assert.equal(roleOperatingGuideForPath('bridger','/bridger/bridge-ai').nextHref,'/bridger/bridge-ai')
assert.equal(roleOperatingGuideForPath('bridger','/bridger/numbers').nextHref,'/weave/market/prospects')
assert.equal(roleOperatingGuideForPath('bridger','/bridger/email-outreach').nextHref,'/bridger/email-outreach')
assert.equal(roleOperatingGuideForPath('bridger','/wallet/deposit-withdraw').nextHref,'/wallet/deposit-withdraw')
assert.equal(transitDirectionForPath('/client/system-switch','/client/dashboard'),'return')
assert.equal(transitDirectionForPath('/bridger/numbers','/bridger/dashboard'),'return')
assert.equal(transitDirectionForPath('/agent/dashboard','/agent/creative'),'forward')
for(const role of ['agent','bridger','client','admin','visitor'])
  assert.equal(trainingBriefsForRole(role).length,3,role+' should retain three training cards')

const art=read('public/weave/bridge-of-radiance-portrait.svg')
assert.ok(art.includes('Bridge of Radiance')&&art.includes('viewBox="0 0 640 1120"'),'Sharp portrait river artwork is bundled locally as scalable vector paths')
assert.ok(art.includes('id="water"')&&art.includes('id="fire"'),'Water and fire form one bridge without a low-resolution raster')
assert.ok(!art.includes('base64,'),'Portrait scene must never embed a stretched thumbnail')

const transit=read('components/world/weave-environment-transit.tsx')
assert.ok(transit.includes('weave-loader-scenery-portrait'),'A resolution-independent portrait scene is rendered at each crossing')
assert.ok(transit.includes('data-weave-loader-role={role}')&&transit.includes('data-weave-loader-destination={destinationPath}'),'Loader responds to role and destination')
assert.ok(transit.includes('returningToWorld')&&transit.includes('Returning to'),'Going back is not described as opening an unrelated system')
assert.ok(transit.includes('transitTrainingForPath(role,destinationPath)'),'Destination tips are contextual and server-free')
assert.ok(transit.includes('data-client-loader-open-world-return'),'Client loader provides a real return route')
assert.ok(!transit.includes("Today's company updates")&&!transit.includes('Select Destination'),'Static image menus and fabricated live updates are absent')
assert.ok(transit.includes('waitForEnvironmentReadiness(mode,configRef.current,controller.signal)'),'The readiness gate is preserved')

const layout=read('app/(app)/layout.tsx')
assert.ok(!layout.includes('AgentSmartGuide')&&!layout.includes('BridgerSmartGuide'),'The intrusive floating guidance is removed from all role pages')
const client=read('app/client/system-switch/page.tsx')
assert.ok(client.includes('data-client-return-weave-open-world')&&client.includes('href="/client/dashboard"'),'Client can return from an active File Folder')
assert.ok(client.includes('data-client-loading-with-open-world-return'),'Client can also return while a File Folder is still loading')
assert.ok(client.includes('Return to Weave Open World'))
const folderLoader=read('components/system-switch/file-folder-environment-loader.tsx')
assert.ok(folderLoader.includes('/weave/bridge-of-radiance-portrait.svg'),'Client private loader uses crisp portrait vector art')
console.log('WEAVE sharp vector art, dynamic role/destination lessons, Bridger guidance and Client open-world return passed')
