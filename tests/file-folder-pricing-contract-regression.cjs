const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')

const pricing=read('lib/file-folder-pricing.ts')
const publicPage=read('app/file-folder/page.tsx')
const prospect=read('components/bridge/file-folder-purchase.tsx')
const purchase=read('app/api/bridge/file-folder/purchase/route.ts')
const publicPurchase=read('app/api/public/file-folder/purchase/route.ts')
const adminPending=read('app/api/admin/bridge-deposits/pending/route.ts')
const adminVerify=read('app/api/admin/bridge-deposits/verify/route.ts')
const systemSwitch=read('app/api/client/system-switch/route.ts')
const metadata=read('app/api/bridge/file-folder/route.ts')
const terms=read('lib/weave-terms.ts')

assert.ok(pricing.includes('standardMinimumFlameCoin: 180'),'Standard begins at 180 Flame Coin')
assert.ok(pricing.includes('standardMaximumFlameCoin: 3000'),'Standard ends at 3,000 Flame Coin')
assert.ok(pricing.includes('proNegotiatedMinimumFlameCoin: 3000'),'Negotiated Pro may reach 3,000 Flame Coin')
assert.ok(pricing.includes('proStartingFlameCoin: 6500'),'Pro normal starting value is 6,500 Flame Coin')
assert.ok(pricing.includes('premiumFlameCoin: 35800'),'Premium is fixed at 35,800 Flame Coin')
assert.ok(pricing.includes("export const FILE_FOLDER_TIERS = ['standard','pro','premium','plus'] as const"),'Pricing contract defines exactly Standard, Pro, Premium and Plus')
assert.ok(pricing.includes('plusFlameCoin: 60000'),'Plus exists as a distinct published File Folder level')
assert.ok(pricing.includes('plusFlameCoin: 60000'),'Plus package is valued at 60,000 Flame Coin')
assert.ok(pricing.includes('plusTrx: 59602'),'Plus purchase is 59,602 TRX')
assert.ok(pricing.includes('plusUsdt: 20000'),'Plus alternative reference is 20,000 USDT')

assert.ok(pricing.includes("if (requested === 'pro')"),'Pro classification requires explicit sale context')
assert.ok(pricing.includes('New Pro sales are negotiated/external sales and must be explicitly marked Pro.'),'Amount-only inference cannot silently turn the 3,000 overlap into Pro')

assert.ok(publicPage.includes("useState<'standard' | 'premium' | 'plus'>('standard')"),'Normal public WEAVE purchase exposes Standard, Premium and Plus, not self-selected Pro')
assert.ok(publicPage.includes('standardMaximumFlameCoin'),'Normal Standard purchase is capped at the Standard building-power maximum')
assert.ok(publicPage.includes('getFileFolderTier(amount, tier)'),'Normal purchase validates the selected tier explicitly')

assert.ok(prospect.includes("useState<'pro' | 'premium'>('pro')"),'Prospect crossing sells Pro by default')
assert.ok(prospect.includes('PRO_STARTING_PRICE'),'Prospect crossing presents the 6,500 Pro starting value')
assert.ok(prospect.includes('PRO_NEGOTIATED_MIN'),'Prospect crossing preserves the 3,000 negotiated minimum')
assert.ok(prospect.includes('fileFolderTier: selectedTier'),'Prospect crossing sends explicit Pro/Premium sale classification')
assert.ok(prospect.includes('PUBLIC_DOOR_THRESHOLD is intentionally retired from prospect purchase gating'),'Prospect source explicitly retires the old Customer Door funding gate')
assert.ok(!prospect.includes('FILE_FOLDER_PUBLIC_DOOR_THRESHOLD_FLAME_COIN'),'Prospect purchase does not consume the build-speed threshold as a purchase gate')

assert.ok(purchase.includes('file_folder_tier varchar(20)'),'Purchase schema persists File Folder sale classification')
assert.ok(purchase.includes('getFileFolderTier(amountFlameCoin, requestedTier)'),'Purchase API validates amount against explicit sale classification')
assert.ok(purchase.includes('amount_trx,file_folder_tier'),'Purchase status reads persisted tier')
assert.ok(publicPurchase.includes('file_folder_tier'),'Public crossing returns persisted tier')
assert.ok(adminPending.includes('purchase.file_folder_tier'),'Administration queue preserves explicit Pro classification')
assert.ok(adminVerify.includes('purchase.file_folder_tier'),'Administration verification preserves explicit Pro classification')
assert.ok(adminVerify.includes('fileFolderTierLabel'),'Administration commission and notification labels understand Pro')
assert.ok(systemSwitch.includes('persistedTier'),'Client runtime restores persisted File Folder tier after crossing')
assert.ok(systemSwitch.includes("getFileFolderTier(amount, 'pro')"),'Legacy Bridge sales retain Pro context inside System Switch')

assert.ok(metadata.includes('proStartingFlameCoin'),'File Folder metadata exposes Pro starting value')
assert.ok(metadata.includes('standardMaximumFlameCoin'),'File Folder metadata exposes Standard maximum')
assert.ok(terms.includes('CURRENT_TERMS_VERSION = 12'),'WEAVE terms version advances with the pricing contract')
assert.ok(terms.includes('PRO_FILE_FOLDER_START'),'WEAVE terms explain Pro separately from Standard and Premium')

console.log('File Folder contract aligned: Standard 180–3,000; Pro starts 6,500; Premium 35,800; Plus 60,000 Flame Coin = 59,602 TRX or 20,000 USDT reference')
