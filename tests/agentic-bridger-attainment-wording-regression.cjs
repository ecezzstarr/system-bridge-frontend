const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const constants=read('lib/world/constants.ts')
const purchase=read('lib/agentic-bridger-purchase.ts')
const lifestyle=read('lib/weave-lifestyle.ts')
const listing=read('app/(app)/weave/lifestyles/page.tsx')
const page=read('app/(app)/weave/lifestyles/agentic-bridger/page.tsx')
const catalog=read('lib/weave-lifestyle-catalog.ts')
const manager=read('app/(app)/manager/dashboard/page.tsx')
const managerAPI=read('app/api/manager/employment/route.ts')
const purchaseAPI=read('app/api/weave/lifestyles/agentic/purchase/route.ts')

assert.ok(constants.includes('AGENTIC_BRIDGER_ONE_TIME_FLAME_COIN: 11'),'Attainment is exactly 11 Flame Coin')
assert.ok(purchase.includes('user_id uuid PRIMARY KEY')&&purchase.includes('FOR UPDATE'),'Ownership is unique and concurrent charges are serialized')
assert.ok(purchase.includes('if (existing.rows.length)')&&purchase.includes('chargedFlameCoin:0'),'Already attained account is not charged again')
assert.ok(purchase.includes('AGENTIC_BRIDGER_ONE_TIME_FLAME_COIN')&&purchase.includes('wallet.id'),'The charge debits the Flame Coin wallet')
assert.ok(purchase.includes('Agentic-Bridger attainment · one-time 11 Flame Coin'),'Wallet history and receipts explain the payment as attainment')
assert.ok(purchaseAPI.includes('alreadyOwned?200:201')&&purchaseAPI.includes('access:await getLifestyleAccess(user.id)'),'Payment returns the already-attained state and refreshed Lifestyle access')
assert.ok(lifestyle.includes('getAgenticBridgerPurchase(userId)')&&lifestyle.includes("source: 'agentic_bridger_one_time'"),'Lifestyle entitlement derives from permanent Agentic-Bridger ownership')
assert.ok(lifestyle.includes('expiresAt: null'),'Agentic-Bridger never expires on a recurring schedule')
assert.ok(listing.includes('Pay 11 Flame Coin once to attain Agentic-Bridger'),'Lifestyle explains the payment attains Agentic-Bridger')
assert.ok(listing.includes('Attain Agentic-Bridger · 11 Flame Coin once'),'Payment action is named as attainment')
assert.ok(listing.includes('Agentic-Bridger then enables Lifestyle access'),'Lifestyle is a benefit of attaining Agentic-Bridger')
assert.ok(!listing.includes('renewContinuance')&&!listing.includes('continuanceRenewing'),'Obsolete monthly Continuance action was removed from the Lifestyle interface')
assert.ok(page.includes('A Bridger attains Agentic-Bridger by paying 11 Flame Coin once'),'Agentic-Bridger page presents one-time attainment')
assert.ok(catalog.includes('Employment still requires its own approval'),'Attainment does not imply being hired')
assert.ok(manager.includes('Pay 11 Flame Coin once to attain Agentic-Bridger'),'Manager employment prerequisite uses correct wording')
assert.ok(managerAPI.includes('one-time payment of 11 Flame Coin attains Agentic-Bridger'),'Manager API communicates same prerequisite')
assert.ok(!listing.includes('recurring Bridger subscription is required'),'No obsolete recurring Bridger fee is advertised')
console.log('Agentic-Bridger one-time attainment and Lifestyle access wording regression passed')
