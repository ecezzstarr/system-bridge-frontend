const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

const gate = read('components/department-entry-ticket-gate.tsx')
const form = read('components/department-entry-loan-support.tsx')
const lib = read('lib/department-entry-loan-support.ts')
const publicApi = read('app/api/department-entry/loan-support/route.ts')
const adminApi = read('app/api/admin/department-entry/loan-support/route.ts')
const adminPage = read('app/(app)/admin/departmental-registration/page.tsx')

assert.match(gate, /!freeTicket && <DepartmentEntryLoanSupport/)
assert.match(form, /Click here to request a loan/)
assert.match(form, /data-entry-loan-support/)
assert.match(form, /This is a request, not funding approval/)
assert.match(form, /x-entry-ticket-token/)
assert.match(form, /Check support status/)
assert.match(lib, /ticket.status !== 'PRESENTED'/)
assert.match(lib, /Number\(ticket.price_flame_coin\) <= 0/)
assert.match(lib, /UNIQUE REFERENCES departmental_entry_tickets\(id\)/)
assert.match(lib, /ON CONFLICT \(ticket_id\) DO NOTHING/)
assert.match(lib, /NOW\(\) - INTERVAL '24 hours'/)
assert.match(lib, /INSERT INTO notifications/)
assert.match(publicApi, /trustedMutationOrigin/)
assert.match(publicApi, /\^\[a-f0-9\]\{64\}/)
assert.match(adminApi, /getSessionByToken/)
assert.match(adminApi, /session\?\.role === 'admin'/)
assert.match(adminApi, /status = \$\{status\}/)
assert.doesNotMatch(adminApi, /issueDepartmentalCode|UPDATE departmental_entry_tickets|balance_trx/)
assert.match(adminPage, /<DepartmentEntryLoanRequestsPanel \/>/)
console.log('PASS: visitor entry-loan support is ticket-scoped, review-only, and separate from payment verification')
