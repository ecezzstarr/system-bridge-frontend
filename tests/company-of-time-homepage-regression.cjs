const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { createHash } = require('node:crypto')
const { join } = require('node:path')
const read = path => readFileSync(join(__dirname, '..', path))
assert.equal(read('app/page.tsx').toString().trim(), "export { default } from './company-grounds/page'")
const grounds = read('app/company-grounds/page.tsx').toString()
assert.match(grounds, /src="\/images\/weave-open-world-home\.jpg"/)
assert.equal(createHash('sha256').update(read('public/images/weave-open-world-home.jpg')).digest('hex'),
  '57b1367249d10e2e9709961cba85073d353943a3a0436c1a614be015cf2fddc1')
assert.match(grounds, /<dialog ref=\{entrances\}[\s\S]*?<nav id="grounds-entrances"[\s\S]*?<\/nav>\s*<\/dialog>/)
assert.match(grounds, /user\.role !== door\.role/)
console.log('Approved image-only homepage and role-aware entrances passed')
