const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')

const engine=read('lib/distribution-assistants.ts')
const main=read('lib/manager-employment.ts')
const route=read('app/api/manager/assistant/route.ts')
const catalog=read('lib/weave-lifestyle-catalog.ts')
const lifestyles=read('app/(app)/weave/lifestyles/page.tsx')
const room=read('app/(app)/manager/dashboard/page.tsx')
const application=read('app/(app)/weave/lifestyles/distribution-assistant/page.tsx')
const migration=read('migrations/20261021_distribution_assistant_managers.sql')

assert.ok(engine.includes('DISTRIBUTION_ASSISTANT_LIMIT = 3'),'No more than three assistants employed company-wide')
assert.ok(engine.includes('DISTRIBUTION_ASSISTANT_MONTHLY_SALARY_NGN = 30_000'),'Assistant monthly salary is ₦30,000')
assert.ok(engine.includes('DISTRIBUTION_ASSISTANT_MONTHLY_REFERRAL_TARGET = 300'),'Each assistant shares 300 monthly referrals')
assert.ok(engine.includes("status='approved'")&&engine.includes('pg_advisory_xact_lock'),'Appointments, not applications, consume capacity under transaction lock')
assert.ok(engine.includes('manager_user_id'),'Approved assistants are connected to the Distribution Manager')
assert.ok(engine.includes("['agent','bridger']")&&engine.includes('getLifestyleAccess(userId)'),'Applicants use existing Agent/Bridger standing')
assert.ok(engine.includes('getManagerEmployment(userId)')&&engine.includes('canReviewAssistants'),'Only employed managers may approve')
assert.ok(engine.includes("date_trunc('month',NOW())"),'Assistant referral count resets each calendar month')
assert.ok(main.includes("created_at>=date_trunc('month',NOW())"),'Existing Manager referral count now resets monthly')
assert.ok(main.includes('MANAGER_MONTHLY_SALARY_NGN = 70_000')&&main.includes('MANAGER_EMPLOYMENT_LIMIT = 3'),'Three existing ₦70,000 Manager roles remain unchanged')
assert.ok(route.includes("body.action==='apply'")&&route.includes("body.action==='approve'"),'Assistant application and appointment API exist')
assert.ok(catalog.includes("DISTRIBUTION_ASSISTANT_LIFESTYLE = 'distribution_assistant'"),'New employment position lives inside Lifestyle')
assert.ok(lifestyles.includes('ASSISTANT DISTRIBUTION MANAGER')&&application.includes('Submit application'),'Assistant application reachable from Lifestyle')
assert.ok(room.includes('data-distribution-assistant-review')&&room.includes('Appoint assistant'),'Manager can appoint assistants')
assert.ok(application.includes('payroll')||application.includes('automatic wallet payment'),'Salary is not falsely promised as automatic payment')
assert.ok(migration.includes('REFERENCES users(id)')&&migration.includes('DEFAULT 30000'),'Assistant appointments have persistent schema')

console.log('Assistant Distribution Manager employment regression checks passed')
