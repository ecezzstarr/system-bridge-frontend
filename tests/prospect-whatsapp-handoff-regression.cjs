const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const ts=require('typescript')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const page=read('app/(app)/weave/market/prospects/page.tsx')
const send=read('app/api/bridger/prospects/[outreachId]/send/route.ts')
const profile=read('app/api/bridger/prospects/route.ts')
for(const file of ['app/(app)/weave/market/prospects/page.tsx','app/api/bridger/prospects/route.ts']){
 const s=ts.createSourceFile(file,read(file),ts.ScriptTarget.Latest,true,file.endsWith('tsx')?ts.ScriptKind.TSX:ts.ScriptKind.TS)
 assert.equal(s.parseDiagnostics.length,0,'Source parses as valid TypeScript/TSX: '+file)
}
assert(page.includes('window.location.assign(waUrl)'),'Android handoff uses same tab')
assert(!page.includes('disabled={sendingId === p.outreachId || !whatsappNumber}'),'Own profile number is not a gate on user-driven WhatsApp')
assert(page.includes('openWhatsApp(target, p.messageSent)'),'Actual first message is prepared in WhatsApp')
const handoff=page.slice(page.indexOf('const handleSend ='),page.indexOf('const handleConfirmSent ='))
assert(!handoff.includes('fetch('),'Opening WhatsApp must never record a sent message')
assert(handoff.includes('rememberPendingWhatsApp'),'Handoff survives same-tab navigation')
const confirmation=page.slice(page.indexOf('const handleConfirmSent ='),page.indexOf('const handleSendBridge ='))
assert(confirmation.includes('confirmedSent:true'),'Only explicit after-send confirmation records contact')
assert(confirmation.includes('keepalive:true'),'The explicit confirmation survives mobile navigation')
assert(page.includes('I actually sent it'),'Action wording must not claim provider-verified delivery')
assert(page.includes('Did not send'),'User can cancel an uncompleted handoff')
assert(page.includes('data-whatsapp-send-requires-confirmation'),'Pending status stays pending until true user confirmation')
assert(page.includes("URLSearchParams(window.location.search).get('tab')==='mine'"),'Direct My Prospects links select actual records')
assert(page.includes('!bridgePermissionIds.includes(p.outreachId)'),'No Bridge handoff without explicit prospect-permission attestation')
assert(page.includes('purchaseCompleted'),'Already-completed package purchase is shown separately from commission reconciliation')
assert(page.includes('Retry package load')&&page.includes('Retry my records'),'Outage never appears as empty inventory')
assert(profile.includes("const whatsappNumber='+'+digits"),'Bridger profile number normalized to international E.164')
assert(profile.includes('Enter a real international WhatsApp number'),'Invalid profile numbers blocked')
assert(send.includes("sent_at = COALESCE(sent_at, NOW())"),'Send timestamps preserved on retries')
assert(send.includes("['sent', 'responded', 'opened', 'converted'].includes"),'Duplicate confirmations do not reset prospect status')
console.log('PASS: truthful WhatsApp handoff, actual send confirmation, permission, E.164 validation, refunds/retry-safe prospect awareness')
