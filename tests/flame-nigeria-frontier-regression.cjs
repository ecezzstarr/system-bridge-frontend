const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const read = name => fs.readFileSync(path.join(root, name), 'utf8')
const engine = read('lib/flame-frontier.ts')
const publicRoute = read('app/api/events/flame/frontier/route.ts')
const adminRoute = read('app/api/admin/flame-frontier/route.ts')
const component = read('components/events/nigeria-flame-frontier.tsx')
const eventGround = read('components/events/position-event-world.tsx')
const adminCommand = read('app/(app)/admin/flame-event/page.tsx')
const home = read('app/page.tsx')
const witnessPage = read('app/flame/frontier/page.tsx')

const rows = [...engine.matchAll(/\{ code: '([A-Z]{2})', name: '([^']+)', zone: '([^']+)' \}/g)]
assert.equal(rows.length, 37, 'Exactly 36 states plus FCT must be registered')
assert.equal(new Set(rows.map(row => row[1])).size, 37, 'Every state code is unique')
assert.equal(rows.filter(row => row[1] === 'FC').length, 1, 'FCT is represented separately')
assert.equal(new Set(rows.map(row => row[2])).size, 37, 'Every state name is unique')
assert.equal(rows.filter(row => row[1] !== 'FC').length, 36, '36 states remain distinct from FCT')
assert.ok(engine.includes("status = 'verified'") && engine.includes('public_opt_in = true'), 'Public totals are verified and consented only')
assert.ok(engine.includes("COUNT(*)::int") && engine.includes('GROUP BY state_code, phase'), 'Counters aggregate real records, not mock data')
assert.ok(engine.includes('getPublicFlameFrontier'), 'Public frontier snapshot resolves from database')
assert.ok(!engine.includes('SELECT id, state_code, sector, phase, title, public_summary, evidence_note\n    FROM weave_flame_frontier'), 'Public snapshot must not select evidence')
assert.ok(publicRoute.includes('requireApiUser(request)') && publicRoute.includes('POSITIONS.has(user.role)'), 'Only signed-in positions can submit')
assert.ok(publicRoute.includes("event.effectiveStatus !== 'active'"), 'Closed and planned events reject new submissions')
assert.ok(publicRoute.includes('body.sharePublicly === true'), 'Public sharing is explicit opt-in')
assert.ok(publicRoute.includes("'submitted'") || publicRoute.includes('RETURNING id, status'), 'New submissions are not automatically verified')
assert.ok(adminRoute.includes("user?.role === 'admin'"), 'Administration owns the review queue')
assert.ok(adminRoute.includes("status = 'submitted'"), 'Reviews are applied to pending submissions only')
assert.ok(adminRoute.includes('reviewNote.length < 12'), 'Reviewer must record an evidence decision')
assert.ok(!component.includes("from '@/lib/flame-frontier'"), 'Client bundle does not import server database')
assert.ok(component.includes('allowSubmission={') === false && component.includes('allowSubmission = true'), 'Shared view supports read-only mode')
assert.ok(eventGround.includes('<NigeriaFlameFrontier />'), 'All event positions see the shared state current')
assert.ok(adminCommand.includes("'/admin/flame-frontier'"), 'Administration can reach the review desk')
assert.ok(home.includes('href="/flame/frontier"') && witnessPage.includes('allowSubmission={false}'), 'World witness is publicly accessible and read-only')

console.log('Flame Nigeria Frontier regression checks passed')
