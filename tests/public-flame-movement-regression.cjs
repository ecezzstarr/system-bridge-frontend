const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')

const root=path.resolve(__dirname,'..')
const read=relative=>fs.readFileSync(path.join(root,relative),'utf8')

const movementEngine=read('lib/public-flame-movement.ts')
const movementRoute=read('app/m/[code]/route.ts')
const ads=read('lib/weave-ads.ts')
const adminAds=read('app/api/admin/ads/route.ts')
const workshop=read('app/(app)/admin/ad-workshop/page.tsx')
const staffRegister=read('app/api/auth/register/route.ts')
const clientRegister=read('app/api/client/weave-register/route.ts')
const purchase=read('app/api/bridge/file-folder/purchase/route.ts')
const verify=read('app/api/admin/bridge-deposits/verify/route.ts')
const pending=read('app/api/admin/bridge-deposits/pending/route.ts')

assert.ok(ads.includes('weave_public_movement_events')&&ads.includes('movement_code')&&ads.includes('PUBLIC_FLAME_PLATFORMS'),'Public Flame Movement extends the existing Ad Workshop schema')
assert.ok(ads.includes("destination.startsWith('/')")&&ads.includes("destination.startsWith('//')"),'Public movement destinations stay inside WEAVE')
assert.ok(movementRoute.includes('PUBLIC_FLAME_MOVEMENT_COOKIE')&&movementRoute.includes("eventType: 'entrance'")&&movementRoute.includes("target.searchParams.set('ref'"),'Public entrances record attribution and preserve referral identity')
assert.ok(adminAds.includes('public_entrances')&&adminAds.includes('public_registrations')&&adminAds.includes('public_file_folder_purchases'),'Administration sees the complete public conversion path')
assert.ok(workshop.includes('Public Flame Movement')&&workshop.includes('Distribution routes')&&workshop.includes('/m/'),'Administration controls public distribution from Ad Workshop')
assert.ok(staffRegister.includes("eventType: 'registration'")&&clientRegister.includes("eventType: 'registration'"),'Registrations retain Public Flame Movement attribution')
assert.ok(purchase.includes("eventType: 'file_folder_purchase'")&&purchase.includes('publicFlameMovementCodeFromRequest'),'File Folder purchases close the Public Flame conversion chain')
assert.ok(movementEngine.includes('recordPublicFlameMovementEvent')&&movementEngine.includes('getPublicFlameMovementAttribution')&&movementEngine.includes('referral_owner_role'),'One attribution engine resolves movement and referral ownership')
assert.ok(purchase.includes('movementBridgerId')&&purchase.includes('bridger_id,movement_code'),'Bridger-owned public movement stays attached to the purchase')
assert.ok(verify.includes('generateFileNumber(bridgerId')&&verify.includes('creditBridgerActivityCommission')&&verify.includes("source: 'file_folder_purchase'")&&verify.includes('replayed: true'),'Administration verification preserves Bridger attribution and idempotent commission movement')
assert.ok(pending.includes('public_bridger_name')&&pending.includes('movement_code'),'Administration sees Public Flame ownership before verification')

console.log('Public Flame Movement regression checks passed')
