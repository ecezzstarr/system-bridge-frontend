const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8')

const application=read('app/api/weave/lifestyles/food-preparation/route.ts')
const appoint=read('app/api/admin/food-preparation-manager/route.ts')
const manager=read('lib/food-preparation-manager.ts')
const route=read('lib/food-preparation-routing.ts')
const agVerify=read('app/api/admin/agility/payment/opay/verify/route.ts')
const elVerify=read('app/api/admin/electrolyte/payment/opay/verify/route.ts')
const cakes=read('app/api/admin/cakes/route.ts')
const cakeSchema=read('lib/carrier-cakes.ts')
const cakeAdmin=read('app/(app)/admin/cakes/page.tsx')
const managerUI=read('app/(app)/weave/lifestyles/food-preparation/page.tsx')
const adminUI=read('app/(app)/admin/food-preparation-manager/page.tsx')
const lifestyle=read('app/(app)/weave/lifestyles/page.tsx')
const catalog=read('lib/weave-lifestyle-catalog.ts')
const migration=read('migrations/20261019_food_preparation_manager.sql')

assert.equal((manager.match(/FOOD_PREPARATION_MANAGER_SALARY_NGN=60000/g)||[]).length,1,'salary ₦60,000')
assert.ok(application.includes("user.role!=='agent'")&&application.includes('getLifestyleAccess(user.id)'),'Agent only, active Lifestyle')
assert.ok(application.includes("WHERE weave_food_preparation_managers.status IN ('rejected','revoked')"),'No applicant self-approves or overwrites approvals')
assert.ok(appoint.includes("admin.role!=='admin'")&&appoint.includes("m.status='pending'"),'Only Administration approves')
assert.ok(appoint.includes("decision==='revoked'")||appoint.includes("$1='revoked'"),'Admin can revoke')
assert.ok(appoint.includes('getLifestyleAccess(people[0].agent_id)'),'Manual manager appointment checks live entitlement')
assert.ok(manager.includes("m.status='approved'")&&manager.includes("u.role='agent' AND u.is_active=true"),'Only approved active Agents see production orders')
assert.ok(manager.includes('WHERE id=$1::uuid AND manager_id=$2::uuid FOR UPDATE'),'Managers cannot manipulate other managers tasks')
assert.ok(manager.includes("order.payment_status!=='paid'"),'No unpaid preparation stages')
assert.ok(manager.includes('weave_food_preparation_task_events')&&manager.includes('INSERT INTO weave_food_preparation_task_events'),'All handoffs logged')
assert.ok(!manager.includes('SET fulfillment_status=$1,admin_note='),'Manager work never overwrites Administration notes')
assert.ok(!manager.includes('UPDATE carrier_cake_orders SET status=$1,admin_note='),'Manager cannot erase cake Admin review note')

for(const [name,code,product] of [['Agility',agVerify,'agility'],['Electrolyte',elVerify,'electrolyte']]){
  const assignment=code.indexOf("assignPaidOrderToPreparationManager(db,'"+product+"'")
  const commit=code.indexOf("await db.query('COMMIT')",assignment)
  assert.ok(assignment>0&&commit>assignment,name+' manager notification is in verified payment transaction')
  assert.ok(code.includes('await ensureFoodPreparationManagerSchema()'),name+' ensures manager schema before transaction')
  assert.ok(code.includes("payment_status='paid'"),name+' paid order must be committed')
}
assert.ok(route.includes('INSERT INTO notifications')&&route.includes("'food_preparation_start'"),'Manager notification sent within paid-order transaction')
assert.ok(route.includes("'no_active_manager'")&&route.includes('food_preparation_unassigned'),'Unassigned paid food escalates to Administration')
assert.ok(route.includes('ON CONFLICT (product,source_order_id) DO NOTHING'),'Duplicate approvals do not resend assignment')
assert.ok(route.includes('delivery_location')&&route.includes('delivery_address'),'Delivery location accompanies alert')
assert.ok(route.includes('customer_phone')&&route.includes('delivery_phone'),'Delivery contacts accompany alert')
