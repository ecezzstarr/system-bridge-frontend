assert.ok(route.includes('event_date')&&route.includes('package_count'),'Event date and quantities accompany instruction')
assert.ok(appoint.includes('notifyManualFoodPreparationAssignment'),'Manual reassignment also notifies selected manager')
assert.ok(appoint.includes('food_preparation_reassigned'),'Previous assignee gets stop-working alert')
assert.ok(cakes.includes("action==='confirm_payment_for_preparation'"),'Admin releases Agent-verified cake separately')
assert.ok(cakes.includes('assignPaidOrderToPreparationManager(client,\'daisy\''),'Cake release assigns a manager in the same transaction')
