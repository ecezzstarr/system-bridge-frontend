const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8')

const chat=read('app/api/bridge/[code]/chat/route.ts')
const visitor=read('components/legacy-bridge-page.tsx')
const support=read('app/api/bridge/[code]/support/route.ts')
const sales=read('lib/file-folder-sales-manager.ts')
const gate=read('app/api/regional-manager/gate/route.ts')
const manager=read('app/api/regional-manager/workspace/route.ts')
const managerPage=read('app/(app)/weave/lifestyles/regional-manager/workspace/page.tsx')
const referral=read('app/api/bridger/referral-commissions/route.ts')
const pageDirectory=read('lib/weave-page-directory.ts')
const purchase=read('app/api/bridge/file-folder/purchase/route.ts')

assert.ok(chat.includes('export async function GET('),'A returning visitor can request their saved chat')
assert.ok(chat.includes('validFingerprint(visitorFingerprint)'),'The visitor must present a random local secret')
assert.ok(chat.includes('visitor_fingerprint=${fingerprint}'),'Chat restoration is bound to the visitor')
assert.ok(chat.includes('visitor_fingerprint=${visitorFingerprint}'),'Chat updates are bound to that visitor')
assert.ok(chat.includes('AND messages=${JSON.stringify(rawHistory)}::jsonb'),'Concurrent tabs cannot silently overwrite chat history')
assert.ok(chat.includes('trustedHistory(rows[0].messages)'),'Replies use recorded history, not forged client role turns')
assert.ok(chat.includes("last.role!=='user'"),'Public caller must submit its own real message')
assert.ok(!chat.includes('UPDATE market_prospect_outreach'),'A URL prospect reference cannot falsely mark a human reply')
assert.ok(visitor.includes('getStoredBridgeSession(code)'),'The returning visitor can discover their saved session')
assert.ok(visitor.includes('storeBridgeSession(code,String(data.sessionId))'),'A new session persists in the visitor browser')
assert.ok(visitor.includes('visitorFingerprint:getFingerprint(code)'),'Visitor support requests send their session secret')
assert.ok(support.includes('AND s.visitor_fingerprint=${visitorFingerprint}'),'Private support history requires the same secret')
assert.ok(sales.includes('ROW_NUMBER() OVER (PARTITION BY sale_key ORDER BY source_priority)'),'Duplicate sales rails are deduplicated before value totals')
assert.ok(sales.includes('FROM deduplicated WHERE rn=1'),'Only canonical confirmed sales enter gross totals')
assert.ok(sales.includes('ownedBridgeSessions'),'Native Bridger Bridge AI sessions are counted alongside legacy crossings')
assert.ok(gate.includes("id:'hope_contacts'")&&gate.includes("id:'hope_bridges'"),'Manager sees outreach and Bridge conversation separately')
assert.ok(gate.includes("AND sent_at IS NOT NULL"),'Outreach is not inferred from candidate purchase')
assert.ok(manager.includes('confirmedOutreach:')&&manager.includes('bridgeConversations:'),'Workplace returns real, separated Hope signals')
assert.ok(managerPage.includes('Bridger-confirmed message sends'),'Manager screen labels self-attested messages')
assert.ok(referral.includes('referralStanding.earningRate'),'Displayed referral share derives from rules, not a stale percentage')
for(const route of ["'/unbuilt-door'","'/bridger/unbuilt-door'","'/admin/unbuilt-door'"]){
  assert.ok(pageDirectory.includes(route),'The platform loader must name '+route)
}
assert.ok(purchase.includes('directBridgerId'),'Client purchase preserves the owning Bridger')
console.log('Hope PHE continuity, manager evidence, financial reporting and release gates passed')
