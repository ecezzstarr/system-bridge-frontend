const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const data = read('lib/enterprise-legions-notebook.ts')
const world = read('components/enterprise/enterprise-legions-notebook-world.tsx')
const route = read('app/(app)/enterprise/legions-notebook/page.tsx')
const recruitment = read('app/(app)/client/enterprise/legions/page.tsx')
const lifestyle = read('app/(app)/weave/lifestyles/legion/page.tsx')
const districts = read('lib/weave-role-districts.ts')
const environments = read('lib/weave-environments.ts')

for (const entry of ['The Lord or Lady Is the General', 'Build Legion Quarters', 'The Agent Enters Through Stability', 'The Bridger Enters Through Hope', 'Set the Terms Before Allegiance', 'Two Sides Confirm the Appointment', 'From Position to Exclusive Legion', 'Carry the Customer Door', 'Share the Value by Record', 'The Legion Returns From Service']) {
  assert.ok(data.includes(entry), 'Enterprise Legions lacks chapter: '+entry)
}
const chapters = data.match(/"key": "/g) || []
assert.equal(chapters.length, 21, 'The notebook must retain all 21 chapters')
assert.ok(data.includes("The Client owns the enterprise"), 'Client ownership remains explicit')
assert.ok(data.includes("Legion Quarters"), 'Recruitment requires quarters')
assert.ok(data.includes("salary, commission, profit share"), 'Pay terms must be distinct')
assert.ok(world.includes('<AdaptiveCanvas'), 'Notebook is a 3D place')
assert.ok(world.includes('No automatic page advance'), 'Pages must not auto-turn')
assert.ok(world.includes('Turn page'), 'Pages must turn manually')
assert.ok(world.includes('step.story'), 'Historic narrative must show')
assert.ok(world.includes('step.action'), 'Every chapter carries a practical action')
assert.ok(world.includes("['client', 'agent', 'bridger', 'admin']"), 'Authorized role access only')
assert.ok(route.includes('EnterpriseLegionsNotebookWorld'), 'Notebook route renders real book')
for (const surface of [recruitment, lifestyle, districts]) assert.ok(surface.includes('/enterprise/legions-notebook'), 'Missing entry link')
assert.ok(environments.includes("key: 'enterprise-legions-notebook'"), 'Notebook needs environment registration')
console.log('Enterprise Legions notebook static checks passed')
