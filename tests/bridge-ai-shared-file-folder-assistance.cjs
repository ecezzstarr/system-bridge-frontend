const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8')
const messages = read('app/api/client/messages/route.ts')
const clientApi = read('app/api/client/bridge-ai/route.ts')
const clientSupport = read('components/system-switch/client-bridge-ai-support.tsx')
const bridgerSupport = read('components/bridger/client-file-folder-assistance.tsx')
const bridgerPage = read('app/(app)/bridger/bridge-ai/page.tsx')

assert.match(messages, /position === 'bridger' \|\| position === 'bridge_ai'/, 'Only assigned Bridgers can access the shared channel')
assert.match(messages, /bridgerOwnsClient\(client, user\.id, clientId\)/, 'Cross-client reads require ownership checking')
assert.match(clientApi, /sender_type IN \('client','bridge_ai','bridger'\)/, 'Client history contains all three participants')
assert.match(clientApi, /FROM client_file_folder_builds/, 'AI uses actual pending File Folder builds')
assert.match(clientApi, /status IN \('building','funding_gate'\)/, 'Only real unfinished work is offered as current construction')
assert.match(clientApi, /role='bridger' AND is_active=true/, 'Client sees an active assigned Bridger only')
assert.match(clientApi, /the Client owns the File Folder and decides what to build/, 'AI must respect Client control')
assert.match(clientApi, /Only the Client's authenticated request can trigger/, 'A human Bridger message is not a billable AI request')
assert.match(bridgerSupport, /position: 'bridge_ai'/, 'Bridger posts to the shared channel')
assert.match(bridgerSupport, /clientId: selectedId/, 'Bridger messages target an assigned Client')
assert.match(bridgerSupport, /\/api\/client\/messages/, 'No duplicate isolated Bridger chat')
assert.match(clientSupport, /message\.sender_type==='bridger'/, 'Bridger messages render in the Client environment')
assert.match(clientSupport, /setInterval/, 'Client can receive new Bridger responses while File Folder stays open')
assert.match(bridgerPage, /<ClientFileFolderAssistance \/>/, 'Bridger Bridge AI mounts the File Folder assistance view')
console.log('Bridge AI three-party assistance source contract passed')
