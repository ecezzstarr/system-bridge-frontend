const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const postcss = require('postcss')

const root = path.resolve(__dirname, '..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const transit = read('components/world/weave-environment-transit.tsx')
const clientFallback = read('components/system-switch/file-folder-environment-loader.tsx')
const css = read('app/weave-readability.css')
const svg = read('public/weave/loader-company-world.svg')
const layout = read('app/layout.tsx')

assert.ok(layout.includes('<WeaveEnvironmentTransit>'), 'One shared transit gate wraps the app')
assert.ok(!clientFallback.includes('fixed inset-0'), 'Client File Folder never installs a second full-screen loader')
assert.match(transit, /isFlameEventVisualRoute\(destinationPath\)/, 'Flame Event artwork is selected by actual destination, not the person’s role')
assert.match(transit, /weave-loader-platform/, 'Company theme is on the shared transit gate')
assert.match(transit, /data-weave-loader-design=\{flameVisual\?/, 'Platform artwork exposes design identity for tests')
assert.match(transit, /data-weave-loader-role=\{role\}/, 'Entry still preserves role identity')
assert.match(transit, /const showFlameBriefing=booting&&flameEventActive/, 'Cold entry retains its event onboarding')
assert.match(transit, /waitForEnvironmentReadiness\(mode,configRef\.current,controller\.signal\)/, 'Readiness gate is preserved')
assert.match(transit, /config\.loading\.lessons\?\.\[audience\]/, 'Administrations controls still drive the lessons')
assert.match(transit, /config\.loading\.autoAdvanceMs/, 'Administrations controls still drive lesson timing')
assert.match(transit, /environmentReady\?'Environment ready/, 'Status is derived from actual route readiness, never invented')
assert.doesNotMatch(transit, /92% built|Customer Door.*Active/, 'The loader cannot claim fictional business activity')
assert.match(css, /url\('\/weave\/loader-company-world\.svg'\)/, 'The shared loader uses its architectural scene')
assert.match(css, /\.weave-loader-platform \.weave-loader-scenery-landscape/, 'Company scene overrides the old Burning River wallpaper')
assert.match(css, /max-height: 610px/, 'Short-phone screen rules are present')
assert.match(css, /prefers-reduced-motion: reduce/, 'Reduced motion remains supported')
postcss.parse(css, {from:'app/weave-readability.css'})
assert.match(svg, /viewBox="0 0 900 580"/, 'Architecture has a scalable viewBox')
assert.match(svg, /<use href="#pavilion"/, 'Multiple connected buildings remain visible')
assert.match(svg, /<desc/, 'SVG retains a text description')
assert.ok(!svg.includes('<script'), 'SVG is presentational, without embedded scripts')
const result = ts.transpileModule(transit, {
  compilerOptions: {jsx:ts.JsxEmit.ReactJSX, module:ts.ModuleKind.ESNext, target:ts.ScriptTarget.ES2022},
  reportDiagnostics: true,
})
const errors = (result.diagnostics || []).filter(item=>item.category===ts.DiagnosticCategory.Error)
assert.equal(errors.length,0,'The shared loader parses as TSX without errors')
console.log('PASS: role-wide architectural loader, original Flame separation, timing, readiness, mobile CSS and TSX')
