const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')

const employment=read('lib/legion-employment.ts')
const auth=read('lib/auth-api.ts')
const lifestyle=read('app/(app)/weave/lifestyles/page.tsx')
const legionPage=read('app/(app)/weave/lifestyles/legion/page.tsx')
const clientMarket=read('app/api/client/enterprise/legion-market/route.ts')
const clientRecruitment=read('app/(app)/client/enterprise/legions/page.tsx')
const enterprisePanel=read('components/system-switch/enterprise-dream-panel.tsx')
const oldLegionRoute=read('app/api/client/enterprise/legions/route.ts')
const appLayout=read('app/(app)/layout.tsx')

assert.ok(employment.includes('legion_lifestyle_applications'),'Legion Lifestyle stores applications and Client invitations')
assert.ok(employment.includes('source_user_id')&&employment.includes('source_role'),'Enterprise Legions preserve the originating Agent or Bridger identity')
assert.ok(employment.includes("employment_status='active'"),'Legion employment has an explicit active state')
assert.ok(auth.includes("role:'legion'")&&auth.includes('baseRole:user.role'),'Active Legion runtime auth suspends normal Agent/Bridger API identity while preserving the base role')
assert.ok(lifestyle.includes('title="LEGION"')&&lifestyle.includes('exclusive employment'),'Lifestyle catalog exposes Legion as Client enterprise employment')
assert.ok(legionPage.includes('Apply to be Legion')&&legionPage.includes('Accept exclusive Legion employment'),'Subscribed Agents and Bridgers can apply or accept Client invitations')
assert.ok(clientMarket.includes("u.role IN ('agent','bridger')")&&clientMarket.includes("subscription_status='active'"),'Client search is limited to available subscribed Agents and Bridgers')
assert.ok(clientRecruitment.includes('Search available people')&&clientRecruitment.includes('Accept as exclusive Legion'),'Client Legion Quarter has search and acceptance controls')
assert.ok(enterprisePanel.includes('/client/enterprise/legions')&&!enterprisePanel.includes('onClick={addLegion}'),'Enterprise Dream routes Legion creation through recruitment instead of manual entry')
assert.ok(oldLegionRoute.includes('Manual Legion creation is closed'),'Legacy manual Legion creation endpoint is retired')
assert.ok(appLayout.includes("router.replace('/weave/lifestyles/legion')")&&appLayout.includes('data-legion-exclusive'),'Protected app runtime locks an accepted Legion into the Client employment environment')

console.log('Legion Lifestyle is subscription-gated, Client-recruited, and exclusive after acceptance')
