const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8')
const css = read('app/company-grounds/grounds.module.css')
const scene = read('app/company-grounds/page.tsx')
assert.match(css, /\.viewport\s*\{[^}]*height:100dvh;[^}]*overflow:auto/)
assert.match(css, /\.scene\s*\{[^}]*aspect-ratio:16\/9/)
assert.match(css, /\.viewport\[data-overview="true"\] \.scene/)
assert.match(scene, /aria-haspopup="dialog"/)
assert.match(scene, /entrances\.current\?\.showModal\(\)/)
assert.match(scene, /href="\/reach-delivery"/)
const reach = read('app/reach-delivery/page.tsx')
assert.match(reach, /<PublicReachRequestForm \/>/)
assert.match(reach, /<ReachRequestTracker \/>/)
console.log('Panoramic framing and public service entrance checks passed')
