const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const transit=read('components/world/weave-environment-transit.tsx')
const css=read('app/weave-readability.css')
const folder=read('components/system-switch/file-folder-environment-loader.tsx')
const mobile=read('public/weave/bridge-of-radiance-portrait.svg')
const landscape=read('public/weave/flame-event/burning-river-world.svg')

assert.ok(mobile.includes('viewBox="0 0 640 1120"'),'Portrait scene has native tall phone framing')
assert.ok(mobile.includes('id="water"')&&mobile.includes('id="fire"')&&mobile.includes('rflow'),'Bridge is formed from independent flowing water and fire')
assert.ok(mobile.includes('prefers-reduced-motion:reduce'),'River respects reduced-motion preference')
assert.ok(landscape.includes('viewBox="0 0 1440 860"'),'Landscape vector scene remains sharp on large screens')
assert.ok(!fs.existsSync(path.join(root,'public/weave/bridge-of-radiance-approved-scene.svg')),'Remove the embedded 150px blurred raster asset')

assert.ok(transit.includes('data-environment-content-state="ready">{children}'),'Render children directly')
assert.doesNotMatch(transit,/weave-loader-stable|revealAfterMs|handleInternalNavigation|setRuntimeCovered\(covered\)/,'No global cover, artificial delay or intercepted navigation')

assert.ok(css.includes('.weave-loading-brief')&&css.includes('animation: none !important'),'Training card never fades/slides/blurs')
assert.ok(css.includes('.weave-loader-lyric-current')&&css.includes('@keyframes weave-loader-lyric-arrive'),'Lesson words change crisply inside the stable reading area')
assert.ok(!css.includes('@keyframes weave-loading-brief-cycle'),'Obsolete blur animation was actually removed')
assert.ok(css.includes('.weave-loader-scenery-portrait')&&css.includes("background-image: url('/weave/bridge-of-radiance-portrait.svg')"),'High-resolution vector is the actual phone background')
assert.ok(css.includes('.weave-loader-scenery-landscape')&&css.includes("background-image: url('/weave/flame-event/burning-river-world.svg')"),'Large screens get a properly framed vector scene')
assert.ok(css.includes('grid-template-rows: minmax(0, 1fr) minmax(0, min(20rem, 46svh))'),'Expanded three-lesson reading panel reserves a stable viewport slot')
assert.ok(css.includes('.weave-loader-card-body')&&css.includes('scrollbar-width: thin'),'Overflowing instructions remain readable and scrollable')
assert.ok(css.includes('.weave-loader-stable :where(h1,h2,p,span,a,section)'),'Text shadow suppression is scoped to loader')
assert.ok(css.includes('html:has(.weave-loader-stable)')&&css.includes('perspective: none !important'),'Fixed loader escapes the global 3D perspective containing block while visible')
assert.ok(css.includes('@media (max-height: 600px)'),'Compact-height Android landscape layout has a dedicated fallback')
assert.ok(css.includes('prefers-reduced-motion: reduce'),'Reduced motion is respected')

assert.ok(folder.includes('data-file-folder-loader="local-status"'),'Client loading has a compact status')
assert.ok(!folder.includes('min-h-[100svh]')&&!folder.includes('weave-file-folder-loader-card'),'Private pending signal has no duplicate viewport-filling screen')
assert.ok(!folder.includes('backdrop-blur-xl'),'Private loader text stays crisp')
console.log('WEAVE loader visual stability: vector artwork, readable fixed-height phone layout, non-blurred copy and role continuity passed')
