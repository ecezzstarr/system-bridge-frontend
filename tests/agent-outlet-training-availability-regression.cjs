const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

const page = read('app/(app)/agent/outlet-training/page.tsx')
const player = read('components/agent/agent-outlet-training-video.tsx')
const electrolyte = read('lib/electrolyte-catalog.ts')
const ember = read('lib/ember-catalog.ts')
const workflow = read('.github/workflows/agent-outlet-training-video.yml')
const production = read('.github/workflows/production-check.yml')

assert.ok(page.includes('ELECTROLYTE_VARIANTS') && page.includes('EMBER_VARIANTS'), 'Training prices must come from current product catalogs')
assert.ok(page.includes('productPricing'), 'The page presents product-size price differences')
assert.ok(page.includes('<AgentOutletTrainingVideo />'), 'Training media uses graceful fallback component')
assert.ok(player.includes('onError={() => setUnavailable(true)}'), 'Missing media is detected')
assert.ok(player.includes('data-agent-training-video="unavailable"'), 'Missing media yields an honest training fallback')
assert.ok(player.includes('/training/agent-outlet-training.mp4'), 'Video points to the published local app asset')
assert.ok(electrolyte.includes("id: 'electrolyte-medium'") && electrolyte.includes('agentSellingUnitPriceNgn: 6000'), 'Medium Electrolyte must remain its own ₦6,000 variant')
assert.ok(ember.includes("id:'ember-large'") && ember.includes('agentSellingUnitPriceNgn:12000'), 'Ember Large remains its own ₦12,000 variant')
assert.ok(workflow.includes('agent-outlet-training.mp4') && workflow.includes('git push origin HEAD:'), 'Dedicated CI generates and publishes playable MP4')
assert.ok(!production.includes('  agent-training-video:'), 'Only one workflow may publish the video to the feature branch')
console.log('Agent training media availability and pricing regression passed')
