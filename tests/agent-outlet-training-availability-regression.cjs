const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')

const page = read('app/(app)/agent/outlet-training/page.tsx')
const player = read('components/agent/agent-outlet-training-video.tsx')
const access = read('lib/company-guidance-access.ts')
const api = read('app/api/agent/training/video/route.ts')
const docker = read('Dockerfile')
const script = read('scripts/build-agent-outlet-training-video.py')
const workflow = read('.github/workflows/agent-outlet-training-video.yml')
const electrolyte = read('lib/electrolyte-catalog.ts')
const ember = read('lib/ember-catalog.ts')

const mediaPath = path.join(root, 'private/agent-training/agent-outlet-training.mp4')
const video = fs.readFileSync(mediaPath)

assert.ok(page.includes('ELECTROLYTE_VARIANTS') && page.includes('EMBER_VARIANTS'), 'Training prices must come from current product catalogs')
assert.ok(page.includes('productPricing'), 'The page presents product-size price differences')
assert.ok(page.includes('<AgentOutletTrainingVideo />'), 'Training includes the approved player')
assert.ok(page.includes("user?.role !== 'agent'"), 'Training page blocks other roles')
assert.ok(access.includes('if (isAgentTrainingRoute(route)) return role === \'agent\''), 'Shared navigation guard blocks non-Agents')
assert.ok(player.includes("user?.role !== 'agent'"), 'Player blocks non-Agent roles')
assert.ok(player.includes("fetch('/api/agent/training/video'"), 'Player uses authenticated media endpoint')
assert.ok(player.includes('Authorization: `Bearer ${token}`'), 'Player provides active bearer token')
assert.ok(player.includes('URL.createObjectURL(media)'), 'Player uses temporary local object URL')
assert.ok(player.includes('data-agent-training-video="unavailable"'), 'Missing video shows a safe fallback')
assert.ok(!player.includes('src="/training/agent-outlet-training.mp4"'), 'Video is not a public URL')
assert.ok(api.includes('getAuthUser(request)'), 'Media authenticates server-side session')
assert.ok(api.includes("user.role !== 'agent'"), 'Media denies non-Agent roles')
assert.ok(api.includes("Cache-Control': 'private, no-store"), 'Media responses must not be publicly cached')
assert.ok(api.includes("'private', 'agent-training', 'agent-outlet-training.mp4'"), 'Media reads only private asset')
assert.ok(!fs.existsSync(path.join(root, 'public/training/agent-outlet-training.mp4')), 'Approved video is absent from public assets')
assert.ok(video.length === 4379652, 'Exact approved 4,379,652-byte video preserved')
assert.equal(video.subarray(4, 8).toString('ascii'), 'ftyp', 'Protected file must be a playable MP4 container')
assert.ok(docker.includes('/app/private/agent-training ./private/agent-training'), 'Docker runner ships private media')
assert.ok(script.includes("OUT=ROOT/'private'/'agent-training'"), 'Future video rendering does not recreate public route')
assert.ok(workflow.includes('test ! -f public/training/agent-outlet-training.mp4'), 'Media CI enforces private path')
assert.ok(electrolyte.includes("id: 'electrolyte-medium'") && electrolyte.includes('agentSellingUnitPriceNgn: 6000'), 'Medium Electrolyte remains ₦6,000')
assert.ok(ember.includes("id:'ember-large'") && ember.includes('agentSellingUnitPriceNgn:12000'), 'Ember Large remains ₦12,000')
console.log('Agent-only training route, private MP4 preservation and product pricing checks passed')
