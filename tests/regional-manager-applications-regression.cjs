const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
const schema = fs.readFileSync(path.join(root, 'migrations/20261028_regional_manager_applications.sql'), 'utf8')
const runtime = fs.readFileSync(path.join(root, 'lib/regional-manager-commission.ts'), 'utf8')
const applicant = fs.readFileSync(path.join(root, 'app/api/regional-manager/applications/route.ts'), 'utf8')
const admin = fs.readFileSync(path.join(root, 'app/api/admin/regional-manager-applications/route.ts'), 'utf8')

assert(schema.includes('weave_regional_manager_applications'), 'Application persistence table exists')
assert(schema.includes('PRIMARY KEY REFERENCES users(id)'), 'One application record per account')
assert(schema.includes("DEFAULT 'pending'") && schema.includes("'approved'") && schema.includes("'rejected'"), 'Application lifecycle is persisted')
assert(runtime.includes('CREATE TABLE IF NOT EXISTS weave_regional_manager_applications'), 'Application schema is initialized at runtime')
assert(applicant.includes("['client', 'bridger', 'agent']"), 'Clients, Bridgers, and Agents can apply without changing their identity')
assert(applicant.includes("status IN ('rejected','withdrawn')"), 'Rejected or withdrawn applicants can submit again')
assert(!/MAX_APPLICATIONS|APPLICATION_LIMIT|LIMIT\s+1000/i.test(applicant + schema), 'No arbitrary 1,000-applicant cap is imposed')
assert(admin.includes('Math.min(100') && admin.includes('OFFSET'), 'Administration reviews applications in bounded, paginated batches')
assert(admin.includes("admin.role !== 'admin'"), 'Application review is Administration-only')
assert(admin.includes("['approve', 'reject'].includes(decision)") && admin.includes("decision === 'approve'"), 'Administration can approve or reject applications')
assert(admin.includes('weave_regional_manager_appointments'), 'Approval creates a Regional Manager appointment while preserving source role')
console.log('Regional Manager application scale and review regression passed')
