const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const distribution=read('app/api/agent/distribution/route.ts')
const app=read('app/(app)/agent/distribution/page.tsx')
const directSales=read('app/api/agility/sales/route.ts')
const carrier=read('app/api/carrier/food/[code]/route.ts')
const training=read('lib/agility-tutorial.ts')
assert.ok(distribution.includes('const officialAmountNgn = packageCount * Number(order.retail_unit_price_ngn)'), 'Server independently calculates outlet amount from verified stock price')
assert.ok(distribution.includes('Math.abs(agreedAmountNgn - officialAmountNgn)'), 'No discounted negotiated supply prices accepted')
assert.ok(distribution.includes('expectedAmountNgn: officialAmountNgn'), 'Agent receives expected official amount on mismatch')
assert.ok(app.includes('agreedAmountNgn:Number(form.cartonCount)*Number(stock.packages_per_box)*Number(stock.retail_unit_price_ngn)'), 'App sends auto calculated official store price')
assert.ok(app.includes('Outlet pays Agent · WEAVE price'), 'App shows store supply total')
assert.ok(app.includes('Stores choose their independent resale markup'), 'Store keeps control of their retail markup')
assert.ok(!app.includes('placeholder="Amount outlet returns"'), 'No editable amount for outlet discount')
assert.ok(directSales.includes('retailUnitPriceNgn = Number(order.retail_unit_price_ngn)'), 'Direct individual sales use official WEAVE snapshot price')
assert.ok(carrier.includes('canonical.customerPriceLocked'), 'Customer Carrier sales follow fixed WEAVE retail price')
assert.ok(training.includes('official WEAVE unit price'), 'Agent training communicates correct selling rule')
console.log('Agent outlet price policy regression passed')
