const fs=require('fs')
const path=require('path')
const assert=require('assert')
const root=path.resolve(__dirname,'..')
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8')

const schema=read('lib/carrier-food.ts')
const migration=read('gcp-migration/carrier-food.sql')
const publicApi=read('app/api/carrier/food/[code]/route.ts')
const publicDoor=read('components/carrier/agent-food-carrier-public.tsx')
const agentApi=read('app/api/carrier/food/route.ts')
const adminApi=read('app/api/admin/carrier-food-payments/route.ts')
const adminPage=read('app/(app)/admin/carrier-food-payments/page.tsx')
const bridgerPage=read('app/carrier/food/[code]/bridger/page.tsx')
const registerApi=read('app/api/auth/register/route.ts')

assert.ok(schema.includes("awaiting_customer_payment")&&schema.includes("awaiting_payment_verification"),'Carrier schema has pre-payment and verification states')
assert.ok(schema.includes('WEAVE_OPAY_ACCOUNT_NUMBER'),'Carrier food reuses WEAVE OPay rail')
assert.ok(migration.includes('opay_transaction_reference')&&migration.includes('payment_verified_at'),'production migration preserves payment verification evidence')
assert.ok(publicApi.includes("action === 'submit_payment'")&&publicApi.includes("action !== 'prepare_payment'"),'public Carrier uses prepare-payment then submit-payment actions')
assert.ok(publicApi.includes("payment_status='proof_submitted'")&&publicApi.includes("status='awaiting_payment_verification'"),'customer payment is submitted before order release')
assert.ok(publicDoor.includes('CONTINUE TO PAYMENT')&&publicDoor.includes('I HAVE PAID — SEND FOR VERIFICATION'),'public UI requires payment before order submission')
assert.ok(agentApi.includes("order.payment_status !== 'paid'")&&agentApi.includes('payment_verified_at'),'Agent cannot fulfill unverified Carrier payment')
assert.ok(adminApi.includes("payment_status='paid',status='requested'")&&adminApi.includes("payment_status='rejected',status='cancelled'"),'Administration controls Carrier payment release')
assert.ok(adminPage.includes('FOOD PAYMENT VERIFICATION')&&adminPage.includes('VERIFY PAID'),'Administration has a payment verification desk')
assert.ok(bridgerPage.includes('WHAT A BRIDGER IS')||bridgerPage.includes('What a Bridger is'),'Carrier has a Bridger explanation before registration')
assert.ok(bridgerPage.includes('BRIDGER_YIELD_RATE')&&bridgerPage.includes('AGENT_LEAD_YIELD_RATE')&&bridgerPage.includes('AGENT_CROSSING_YIELD_RATE'),'Bridger explanation derives Bridger and Agent earnings from canonical rules')
assert.ok(registerApi.includes('assigned_agent_id'),'Agent-referred Bridger registration keeps assigned Agent relationship')

console.log('Carrier food payment-first checkout and Bridger explanation regression checks passed')
