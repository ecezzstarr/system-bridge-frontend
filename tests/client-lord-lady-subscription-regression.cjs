const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=x=>fs.readFileSync(path.join(root,x),'utf8')
const subscription=read('lib/client-monthly-subscription.ts')
const route=read('app/api/client/monthly-subscription/route.ts')
const clientRegister=read('app/client/register/page.tsx')
const clientRegisterApi=read('app/api/client/weave-register/route.ts')
const staffRegister=read('app/(auth)/register/page.tsx')
const staffRegisterApi=read('app/api/auth/register/route.ts')
const enterprise=read('app/api/client/enterprise/route.ts')
const admin=read('app/api/admin/enterprise/route.ts')
const panel=read('components/system-switch/enterprise-dream-panel.tsx')
const lifestyle=read('lib/weave-lifestyle.ts')
const notebook=read('lib/enterprise-legions-notebook.ts')
const header=read('components/app-header.tsx')

assert.ok(subscription.includes('CLIENT_MONTHLY_SUBSCRIPTION_FLAME_COIN = 600'),'Client month is 600 Flame Coin')
assert.ok(subscription.includes("registered === 'male' ? 'lord' : registered === 'female' ? 'lady'"),'Title follows gender at registration')
assert.ok(subscription.includes('client_monthly_subscriptions'),'Paid Client subscription is independently recorded')
assert.ok(subscription.includes("UPDATE wallets SET balance_trx=balance_trx-$1"),'600 FC is deducted atomically from Client wallet')
assert.ok(subscription.includes("await conn.query('BEGIN')")&&subscription.includes('FOR UPDATE'),'Wallet subscription uses a transaction and locking')
assert.ok(subscription.includes('issueWeaveReceipt'),'A subscription produces a payment receipt')
assert.ok(subscription.includes("payment_status='paid'"),'Title eligibility requires verified payment')
assert.ok(clientRegister.includes('Gender (registration identity)')&&clientRegisterApi.includes('gender: rawGender'),'Client registration explicitly captures gender')
assert.ok(staffRegister.includes('Gender')&&staffRegisterApi.includes('normalizeRegisteredGender(body.gender)'),'Staff registration also captures gender')
assert.ok(route.includes('complete_registration_gender'),'Legacy Clients without gender can complete registration once')
assert.ok(enterprise.includes('monthlyStanding.title')&&!enterprise.includes('cleanText(body.requestedPosition'),'Enterprise title cannot be manually chosen')
assert.ok(enterprise.includes("folder.enterprise_status === 'approved'"),'A subscribed Lord/Lady is not misclassified as an approved enterprise')
assert.ok(admin.includes('getClientMonthlyStanding'),'Admin approval verifies current Client subscription')
assert.ok(panel.includes('Subscribe · 600 Flame Coin / month'),'UI opens paid monthly subscription')
assert.ok(!panel.includes('Requested position<select'),'Lord/Lady is not manually selected')
assert.ok(lifestyle.includes("if (role === 'client')")&&lifestyle.includes('getClientMonthlyStanding(userId)'),'Client Lifestyle requires verified subscription')
assert.ok(notebook.includes('Real Client product sales fund expenses'),'Enterprise economics focus on Client-owned products')
assert.ok(header.includes('Client · File Folder'),'Unsubscribed Clients are not called Lord/Lady in header')
console.log('Client gender registration, paid 600 Flame Coin Lord/Lady elevation and Client product surplus policy checks passed')
