const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const employment=read('lib/manager-employment.ts')
const assistants=read('lib/distribution-assistants.ts')
const updates=read('lib/distribution-team-updates.ts')
const adminApi=read('app/api/admin/distribution-employment/route.ts')
const teamApi=read('app/api/manager/team/route.ts')
const managerPage=read('app/(app)/manager/dashboard/page.tsx')
