// The actual pricing helper computes free blueprints, kit totals and missing kits.
const code=quote.replace(/export type BlueprintCostFields=\{[\s\S]*?\n\}/,'').replace(/export function quoteFileFolderBlueprint\(blueprint:BlueprintCostFields,ownedInput=0\)/,'function quoteFileFolderBlueprint(blueprint,ownedInput=0)')
const func=Function(code+'\nreturn quoteFileFolderBlueprint')()
let result=func({required_item_key:null,required_item_quantity:0},0)
assert.equal(result.requiredMaterialCost,0,'No-kit blueprints must display 0, not NaN')
assert.equal(result.acquireCost,0)
result=func({required_item_key:'store_kit',required_item_name:'Store Kit',required_item_quantity:3,required_item_price_flame_coin:120,required_item_published:true},1)
assert.equal(result.requiredMaterialCost,360)
assert.equal(result.acquireCost,240)
assert.equal(result.materialMissing,2)
assert.equal(result.buildActionCost,0)
result=func({required_item_key:'missing_kit',required_item_quantity:1},0)
