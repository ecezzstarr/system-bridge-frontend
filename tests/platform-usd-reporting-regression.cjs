const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const read = p => fs.readFileSync(path.join(__dirname,'..',p),'utf8')
const src = read('lib/platform-currency.ts')
const js = ts.transpileModule(src,{
  compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022},
  reportDiagnostics:true,
})
assert.equal((js.diagnostics || []).filter(x=>x.category===ts.DiagnosticCategory.Error).length,0)
const mod={exports:{}}
new Function('module','exports',js.outputText)(mod,mod.exports)
const { PLATFORM_CURRENCY_CODE, legacyUnitsToUsd }=mod.exports
assert.equal(PLATFORM_CURRENCY_CODE,'USD')
assert.equal(legacyUnitsToUsd(10,0.25),2.5)
assert.equal(legacyUnitsToUsd(-5,0.25),-1.25)
assert.equal(legacyUnitsToUsd(0,0.25),0)
assert.equal(legacyUnitsToUsd(100,0),null)
assert.equal(legacyUnitsToUsd(NaN,0.25),null)
assert.equal(legacyUnitsToUsd(12,NaN),null)
const wallet=read('app/api/wallet/balance/route.ts')
const ledger=read('app/api/ledger/route.ts')
const page=read('app/(app)/wallet/deposit-withdraw/page.tsx')
const record=read('app/(app)/ledger/page.tsx')
assert(wallet.includes('usdEquivalent'), 'Wallet exposes labelled read-only USD estimate')
assert(wallet.includes("currency: 'System Switch'"), 'Spendable legacy wallet still uses its actual units')
assert(wallet.includes("legacyCurrencyCode: 'FLAME_COIN'"), 'Accounting code stays identifiable')
assert(ledger.includes('usdValuation'), 'Record includes quoted USD estimate')
assert(page.includes('Estimated USD equivalent'), 'Wallet labels USD estimate rather than cash')
assert(record.includes('Estimated USD equivalent'), 'Ledger labels USD estimate rather than cash')
assert(src.includes('coingecko_trx_usd'),'USD valuation uses live TRX/USD quotation')
assert(read('docs/platform-usd-transition.md').includes('Required before final USD cutover'))
console.log('USD target and legacy-valuation controls: passed')
