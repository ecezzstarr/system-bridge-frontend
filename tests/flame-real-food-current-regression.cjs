const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8')

const api=read('app/api/events/flame/food-current/route.ts')
const ground=read('components/events/position-event-world.tsx')
const display=read('components/events/flame-food-current.tsx')
const orders=read('app/api/flame/food/orders/route.ts')
const guestOrders=read('app/api/carrier/food/[code]/farm/route.ts')
const model=read('lib/food-bridge.ts')

assert.ok(!ground.includes('<FlameFoodCurrent />'),'The removed food statistics panel is not mounted in Flame Event')
assert.ok(ground.includes('<BurningRiverOfficialGateway staff'),'Customer Door access remains available from the living-world entrance')
assert.ok(api.includes('ensureFoodBridgeSchema()'),'Current reads real Food Bridge storage')
assert.ok(api.includes('FROM weave_food_direct_orders o'),'Event reads actual household orders')
assert.ok(api.includes('FROM weave_food_surplus l'),'Event reads actual farmer offers')
assert.ok(api.includes('FLAME_EVENT.startsAt')&&api.includes('FLAME_EVENT.endsAt'),'Movement is scoped to Company Loop 1')
assert.ok(api.includes("f.status='approved'")&&api.includes("u.role='agent'"),'Public offers require approved Agent supplier')
assert.ok(api.includes('o.destination_state')&&api.includes('f.state AS origin_state'),'Corridors are source-to-destination movements')
assert.ok(!api.includes('o.buyer_phone_private')&&!api.includes('o.buyer_name')&&!api.includes('o.destination_area')&&!api.includes('o.guest_order_digest'),'Event never queries personal recipient details')
assert.ok(!api.includes('f.contact_private')&&!api.includes('o.quote_note'),'Event never publishes private contact or transport notes')
assert.ok(api.includes("'dispatched'")&&api.includes("'delivered'"),'Dispatch and buyer receipt are counted separately')
assert.ok(display.includes('Household reported receipt')&&display.includes('not verified payments'),'Delivery and paid outcomes are not misrepresented')
assert.ok(display.includes('offers.length===0')&&display.includes('routes.length===0'),'No invented food or movement when feed is empty')
assert.ok(display.includes('offer.carrierPath')&&api.includes('/carrier/food/'),'Real Agent Carrier link drives next customer action')
assert.ok(model.includes('carrier_referral_code')&&guestOrders.includes('carrier_referral_code'),'Visitor transactions carry Agent source attribution')
assert.ok(orders.includes("buyer_user_id=$1::uuid"),'Signed in Lifestyle orders remain supported')
console.log('Flame Event direct food movement regression checks passed')
