const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const vm=require('node:vm')
const ts=require('typescript')
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8')
const src=read('lib/weave-open-world-domains.ts')
const c=ts.transpileModule(src,{compilerOptions:{
  module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,
}}).outputText
const moduleExports={}
vm.runInNewContext(c,{exports:moduleExports,Math,Number,String},{filename:'lib/weave-open-world-domains.ts'})
const {projectPublicWorldDomain,worldLocationForSlot,formatWorldMovement}=moduleExports
const first=worldLocationForSlot(12)
assert.equal(first.slot,12)
assert.equal(worldLocationForSlot(12).x,first.x)
assert.notDeepEqual(worldLocationForSlot(13),first)
assert.ok(Number.isFinite(first.x)&&Number.isFinite(first.z))
const privateRow={id:'domain-1',slot:12,tier:'standard',
  public_name:'PRIVATE FAMILY BUSINESS',public_slug:'private-client-door',
  open_door:false,building_count:1,operating_count:0,completed_count:0,
  published_offers:12,forming_progress:35,available_for_collaboration:false,
  accepted_connections:0,file_number:'PRIVATE-123',private_notes:'NOT FOR PUBLIC'}
const formed=projectPublicWorldDomain(privateRow)
assert.equal(formed.stage,'forming')
assert.equal(formed.building,true)
assert.equal(formed.activity.buildProgress,35,'Public scaffolding tracks real Client construction percent')
assert.equal(formed.customerDoor.href,null)
assert.equal(formed.publicName.includes('PRIVATE FAMILY BUSINESS'),false)
assert.equal(formed.publishedOffers,0)
assert.equal(JSON.stringify(formed).includes('PRIVATE-123'),false)
assert.equal(JSON.stringify(formed).includes('NOT FOR PUBLIC'),false)
assert.equal(formed.collaborationAvailable,false)
const commissioned=projectPublicWorldDomain({...privateRow,tier:'plus',
  building_count:0,completed_count:4,operating_count:2,
  open_door:true,public_name:'Radiant Office',public_slug:'radiant-office',published_offers:5})
assert.equal(commissioned.tier,'plus')
assert.equal(commissioned.stage,'operating')
assert.equal(commissioned.customerDoor.href,'/market/radiant-office?via=system-switch')
assert.equal(commissioned.publishedOffers,5)
assert.equal(commissioned.publicName,'Radiant Office')
assert.ok(commissioned.buildLevel>formed.buildLevel)
assert.equal(projectPublicWorldDomain({...privateRow,operating_count:3}).stage,'expanding')
const acceptedOnly=projectPublicWorldDomain({...privateRow,
  operating_count:1,accepted_connections:1,linked_projects:0})
assert.equal(acceptedOnly.stage,'operating','An accepted invitation is not proof of expansion')
assert.equal(acceptedOnly.activity.jointFormations,0)
const genuineJoint=projectPublicWorldDomain({...privateRow,
  operating_count:1,accepted_connections:1,linked_projects:1})
assert.equal(genuineJoint.stage,'expanding','Two verified systems in one accepted project develop castles')
assert.equal(genuineJoint.activity.jointFormations,1)
assert.ok(genuineJoint.buildLevel>acceptedOnly.buildLevel)
assert.equal(formatWorldMovement('connection_accepted'),'Two Clients formed a company-event connection')

const purchased=read('lib/file-folder-purchase-activation.ts')
const db=read('lib/weave-open-world-store.ts')
const api=read('app/api/events/flame/open-world/route.ts')
const client=read('app/api/client/company-loop-connections/route.ts')
const map=read('components/events/burning-river-live-world.tsx')
const gate=read('components/events/burning-river-official-gateway.tsx')
const route=read('app/flame-event/world/page.tsx')
const staff=read('components/events/position-event-world.tsx')
const visitor=read('components/events/flame-event-public-mobile.tsx')
const migration=read('migrations/20261023_burning_river_open_world_domains.sql')
assert.ok(purchased.includes('provisionPurchasedWorldDomain('),'Client activation adds permanent world node')
assert.ok(db.includes('ON CONFLICT(file_number)')&&migration.includes('world_slot bigint GENERATED BY DEFAULT AS IDENTITY'),
  'Repeated activation cannot relocate purchased folder')
assert.ok(db.includes("b.status='building'")&&db.includes("b.status='active'")&&
 db.includes("c.status='accepted'"),'World reflects actual progress and accepted connections')
assert.ok(api.includes('matureElapsedCustomerDoors(sql)')&&api.includes("'Cache-Control':'no-store'"),
  'Map read is current without forging timed-door completion')
assert.ok(!api.includes('buyer_email')&&!api.includes('file_number:')&&!api.includes('client_id:'),
  'Public API never serializes private owner fields')
assert.ok(client.includes('c.requested_by<>')&&client.includes("c.status='pending'")&&
 client.includes('ON CONFLICT (loop_key,domain_a,domain_b) DO NOTHING'),
 'No self approval, replayed invitation or unsupported acceptance')
assert.ok(client.includes("action==='propose_project'")&&client.includes("action==='accept_project'")&&
 client.includes("action==='contribute_system'"),
 'Joint work requires a proposal, partner approval and real operating Client system')
assert.ok(client.includes("b.client_id=${domain.client_id}::uuid")&&
 client.includes("b.status='active'"),
 "A Client cannot contribute another person\'s or an inactive system")
assert.ok(db.includes('idx_weave_open_world_projects_connection')&&
 db.includes("active_system.status='active'")&&
 migration.includes('weave_open_world_project_contributions'),
 'Public domain maturity uses independently active contributions from both worlds')
assert.ok(map.includes('MovingBurningRiver')&&map.includes('DomainCastle')&&map.includes('<AdaptiveCanvas')&&
 map.includes('request_connection')&&map.includes('respond_connection'),
 'Real 3D castle and multiplayer interaction operate from actual records')
assert.ok(!map.includes('WeaveEmbodiedAvatar')&&!map.includes('joystick')&&!map.includes('soldiers'),
 'World is about Client systems and company interaction, not warfare')
assert.ok(gate.includes("burning-river-crossing-official.webp")&&
 map.includes("burning-river-open-world-official.webp"),
 'Both official approved images are referenced; no alternate concept image')
assert.ok(gate.includes('href={worldHref}')&&route.includes('<BurningRiverLiveWorld role={role}/>'),
 'Clickable crossing opens real shared world route')
assert.ok(gate.includes('encodeURIComponent(carrierCode)')&&
 route.includes('<FlameEventFoodStore carrierCode={carrierCode}/>'),
 'Agent Carrier attribution remains connected while visitors cross into the shared world')
assert.ok(staff.includes('<BurningRiverOfficialGateway staff/>')&&
 visitor.includes('<BurningRiverOfficialGateway carrierCode={carrierCode}/>'),
 'Same worlds accessible from staff and public entrances')
assert.ok(api.includes('await readyWorldStorage(sql)')&&
 api.includes('lastReconciliation')&&api.includes('initialization'),
 'Open-world polling cannot recreate schema/catalog on every public request')
assert.ok(db.includes("AND d.tier='unclassified'"),
 'Older staff grants cannot silently downgrade verified purchased worlds')
assert.ok(client.includes(".catch((error)=>console.error('[Burning River notification delivery]',error))"),
 'Notification service failures do not falsely report an already committed event action as failed')

console.log('PASS: Purchased Client domains, protected public records, approved art paths, noncombat interaction')
