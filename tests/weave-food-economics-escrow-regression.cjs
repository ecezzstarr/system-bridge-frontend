const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const r=p=>fs.readFileSync(path.join(root,p),'utf8')
const agility=r('lib/agility-catalog.ts')
const electrolyte=r('lib/electrolyte-catalog.ts')
const economics=r('lib/weave-food-economics.ts')
const cakes=r('lib/cake-catalog.ts')
const cakeApi=r('app/api/agent/cakes/route.ts')
const cakeModel=r('lib/carrier-cakes.ts')
const agentCarrier=r('app/(app)/weave/carrier/food/page.tsx')
const shareImage=r('app/carrier/food/[code]/opengraph-image.tsx')
const farmerModel=r('lib/food-bridge.ts')
const escrow=r('lib/food-escrow.ts')
const admin=r('app/api/admin/food-escrow/route.ts')
const guest=r('app/api/carrier/food/[code]/farm/order/route.ts')
const buyer=r('app/api/flame/food/orders/route.ts')
const farmer=r('app/api/flame/food/farmer/route.ts')
const publicUI=r('components/carrier/agent-farm-carrier-public.tsx')
const buyerUI=r('components/flame-food/farmer-household-food-bridge.tsx')

assert.ok(agility.includes('AGILITY_RETAIL_UNIT_PRICE_NGN = 4000'),'Agility costs buyer ₦4,000')
assert.ok(agility.includes('AGILITY_AGENT_BOX_PRICE_NGN = 30000'),'Agility stock cost for ten is ₦30,000')
assert.ok(agility.includes('AGILITY_PACKAGES_PER_BOX = 10'),'Carton contains ten units')
assert.ok(agility.includes('AGILITY_AGENT_GROSS_PROFIT_PER_BOX_NGN'),'Agent carton earnings follow canonical calculation')
assert.ok((electrolyte.match(/agentBuyUnitPriceNgn: 3000/g)||[]).length===2,'Both Electrolyte bowl sizes have ₦3,000 unit Agent cost')
assert.ok((electrolyte.match(/agentSellingUnitPriceNgn: 4000/g)||[]).length===2,'Both Electrolyte bowl sizes have ₦4,000 retail price')
assert.ok(economics.includes('customerPriceLocked: true'),'Both official company food brands have fixed customer prices')
assert.ok(economics.includes('agentGrossProfitPerBoxNgn: retailBoxValueNgn - agentBoxPriceNgn'),'Agent carton margin derives from cash spread, not a second fee')
assert.ok(cakes.includes('DAISY_CAKE_SLICE_PRICE_NGN=5000'),'Daisy Slice exactly ₦5,000')
assert.ok(cakes.includes('DAISY_AGENT_COMMISSION_NGN=1000'),'Daisy gives selling Agent ₦1,000 per completed sale')
assert.ok(cakes.includes('weaveShareNgn:cakePriceNgn-DAISY_AGENT_COMMISSION_NGN'),'Daisy earning comes out of the cake price')
assert.ok(cakeApi.includes('agent_commission_ngn=$9,weave_share_ngn=$10'),'Actual order stores both Agent and company share')
assert.ok(cakeModel.includes('agent_commission_ngn numeric(14,2)'),'Cake ledger preserves commission')
assert.ok(agentCarrier.includes('₦10,000 per full carton (10)'),'Agent home explains daily carton earnings')
assert.ok(shareImage.includes('₦4,000 EACH · AGENT EARNS ₦1,000'),'Public generated official share image matches pricing')

assert.ok(farmerModel.includes('weave_commission_ngn numeric(18,2) NOT NULL DEFAULT 0 CHECK (weave_commission_ngn=0)'),'Database prohibits farmer commission')
assert.ok(farmerModel.includes('CHECK (seller_payout_ngn=buyer_total_ngn)'),'Full buyer total is owed to farmer, with no hidden WEAVE markup')
assert.ok(farmerModel.includes('verified_bank_reference'),'Escrow independent bank reconciliation is stored')
assert.ok(escrow.includes('WEAVE_FARM_COMMISSION_NGN = 0'),'Farmer commission canonical zero')
assert.ok(escrow.includes('FARM_ESCROW_ACCOUNT_NUMBER = WEAVE_OPAY_ACCOUNT_NUMBER'),'Buyer pays company receiving account')
assert.ok(escrow.includes("status='proof_submitted'"),'Buyer proof is not automatically confirmed money')
assert.ok(buyer.includes('submitFarmEscrowProof(client,id'),'Signed-in buyer proof requires authenticated order ownership')
assert.ok(guest.includes('digestGuestOrderKey(key)')&&guest.includes('submitFarmEscrowProof(client,order.id'),'Guest requires private token, not account registration')
assert.ok(buyer.includes('initializeFarmEscrow(client,id')&&guest.includes('initializeFarmEscrow(client,order.id'),'Both buyers snapshot exact accepted quote')
assert.ok(farmer.includes("const expected=action==='confirm'?'requested':'funds_held'"),'Farmer cannot dispatch on an accepted-but-unpaid quote')
assert.ok(farmer.includes("e.status='held' AND e.verified_at IS NOT NULL"),'Farmer dispatch requires verified held funds')
assert.ok(admin.includes("admin.role!=='admin'"),'Only Admin reconciles bank money')
assert.ok(admin.includes("order.status!=='proof_submitted'")&&admin.includes("order.order_status!=='accepted'"),'Only proof pending can be verified')
assert.ok(admin.includes("Math.abs(amount-Number(order.buyer_total_ngn))>0.001"),'Admin must reconcile exact buyer payment amount')
assert.ok(admin.includes("status='funds_held'")&&admin.includes("'farm_payment_held'"),'Actual verified funds alert farmer with instructions')
assert.ok(admin.includes("order.status!=='release_due'")&&admin.includes("order.order_status!=='delivered'"),'Seller payout cannot precede buyer receipt')
assert.ok(admin.includes("body.confirmedBankTransfer===true"),'Manual payout requires explicit completed bank transfer acknowledgement')
assert.ok(admin.includes('payout_reference')&&admin.includes('payout_recorded_by'),'Actual transfer proof and reviewer are recorded')
assert.ok(admin.includes('record_refund')&&admin.includes("status='disputed'"),'Dispute blocks payout and supports actual refund record')
assert.ok(publicUI.includes('data-guest-farm-weave-payment')&&publicUI.includes('paymentAccountNumber'),'Guest sees WEAVE escrow instructions')
assert.ok(buyerUI.includes('data-food-farm-escrow-payment')&&buyerUI.includes('submit_payment_proof'),'Signed-in buyer sees payment workflow')
assert.ok(buyerUI.includes("o.status==='funds_held'")&&buyerUI.includes("action:'set_payout_account'"),'Farmer sees only confirmed dispatch and can privately set receiving account')
assert.ok(!publicUI.includes('WEAVE has not collected or verified any payment through this farm order flow.'),'Retired misleading marketing removed')
