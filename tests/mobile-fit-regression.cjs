const fs = require('fs')
const path = require('path')
const assert = require('assert')

const root = path.resolve(__dirname, '..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')

const rootLayout = read('app/layout.tsx')
const mobile = read('app/weave-mobile.css')
const dj = read('components/dj-broadcast-player.tsx')
const header = read('components/app-header.tsx')
const dashboard = read('components/world/weave-dashboard-world.tsx')

assert.ok(rootLayout.includes("import './weave-mobile.css'"), 'Root layout loads the global mobile-fit layer')
assert.ok(mobile.includes('@media (max-width: 767px)'), 'Mobile-fit rules are phone-scoped')
assert.ok(mobile.includes('body :where(main,section,article,form,fieldset) [class*="min-w-[2"]'), 'Legacy route-content minimums are allowed to shrink on phones')
assert.ok(mobile.includes('body :where(main,section,article,form,fieldset) [class*="w-["]'), 'Arbitrary desktop widths are constrained inside route content only')
assert.ok(!mobile.includes('body [class*="w-["]'), 'Phone fitting does not globally squeeze floating top-bar controls')
assert.ok(mobile.includes('.weave-header [data-weave-floating-ui="true"]'), 'Floating header panels use viewport-safe sizing instead of avatar-parent sizing')
assert.ok(mobile.includes('.weave-header .w-80') && mobile.includes('calc(100vw - 1rem)'), 'Notification panel remains fully inside narrow phone viewports')
assert.ok(mobile.includes('body :where(table)') && mobile.includes('overflow-x: auto'), 'Dense tables scroll locally instead of widening the page')
assert.ok(header.includes('data-weave-phone-order="presence-interaction-value-signal"'), 'Phone top chrome declares the WEAVE movement order')
for (const station of ['presence','interaction','value','signal']) {
  assert.ok(header.includes(`data-phone-chrome="${station}"`), `Phone header keeps ${station} as a distinct ordered station`)
}
assert.ok(header.includes("'Hope'") && header.includes("'Stability'") && header.includes("'Lord/Lady'") && header.includes("'A Cat'"), 'Phone Presence station preserves WEAVE position language')
assert.ok(dashboard.includes('data-mobile-world-order="presence-district-place-service"'), 'Phone role world keeps Presence before District before Place and secondary services')
assert.ok(dashboard.indexOf('data-role-presence-gate={role}') < dashboard.indexOf('Presence → District → Place'), 'Phone world starts from Presence before district travel')
assert.ok(dashboard.indexOf('Presence → District → Place') < dashboard.indexOf('data-mobile-world-service="after-movement"'), 'Shared services no longer jump ahead of role movement on phones')
assert.ok(dj.includes('data-weave-dj-mirror="true"'), 'Global DJ exposes the mirror surface selector')
assert.ok(mobile.includes('[data-weave-dj-mirror="true"]') && mobile.includes('max-width: 5.25rem !important'), 'Phone DJ collapses to a compact mirror pill')
assert.ok(mobile.includes('left: auto !important') && mobile.includes('right: max(.5rem, env(safe-area-inset-right)) !important'), 'Phone DJ ignores saved drag coordinates and stays beside the header')
assert.ok(mobile.includes('button:first-child') && mobile.includes('div:nth-child(3)'), 'Phone DJ hides drag and long metadata instead of covering content')

console.log('mobile-fit-regression: ok')
