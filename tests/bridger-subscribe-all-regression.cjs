const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const page=read('app/(app)/bridger/subscription/page.tsx')
const bundleApi=read('app/api/bridger/subscription/all/route.ts')
const bundleEngine=read('lib/bridger-subscribe-all.ts')
const monthlyApi=read('app/api/bridger/subscription/route.ts')
const monthlyEngine=read('lib/bridger-subscription.ts')
const cron=read('app/api/cron/subscription-check/route.ts')
const bridgeMonthly=read('app/api/bridger/bridge-ai/subscribe/route.ts')
const bridgeOpen=read('app/api/bridger/bridge-ai/route.ts')
const echo=read('lib/echo-db.ts')
const echoApi=read('app/api/echo/subscribe/route.ts')
assert.ok(page.includes('No Subscription')&&page.includes('8 Flame Coin')&&page.includes('11 Flame Coin'),'Bridger legacy URL explains new free position and purchases')
assert.ok(monthlyApi.includes('retired:true')&&monthlyApi.includes('status:410'),'Monthly Bridger POST can no longer charge')
assert.ok(bundleApi.includes('retired:true')&&bundleApi.includes('status:410'),'Monthly bundle API is retired')
assert.ok(monthlyEngine.includes("reason:'retired'")&&!monthlyEngine.includes('UPDATE wallets'),'Monthly Continuance cannot debit wallets')
assert.ok(bundleEngine.includes("reason:'retired'")&&!bundleEngine.includes('UPDATE wallets'),'Monthly bundle cannot debit wallets')
assert.ok(cron.includes('autoRenewed:0')&&!cron.includes('autoDeductContinuance'),'Cron does not charge or remind Bridgers')
assert.ok(bridgeMonthly.includes('status:410')&&bridgeMonthly.includes('templateOpenFlameCoin'),'Bridge AI subscription route is permanently retired')
assert.ok(bridgeOpen.includes('BRIDGE_AI_TEMPLATE_OPEN_FLAME_COIN')&&bridgeOpen.includes('UPDATE wallets')&&bridgeOpen.includes('INSERT INTO bridge_ais'),'New Bridge AI template opening performs atomic debit and creation')
assert.ok(echo.includes('chargedFlameCoin:0')&&echoApi.includes('getEchoContinuance'),'Echo activation is free')
console.log('Retired monthly Bridger products and free Echo regression checks passed')
