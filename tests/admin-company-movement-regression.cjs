// Contracts for read-only Administrations movement intelligence.
// These checks deliberately protect payment-status boundaries and route access.
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8')
const api=read('app/api/admin/company-movement/route.ts')
const ui=read('app/(app)/admin/company-movement/page.tsx')
const entry=read('app/(app)/admin/control-center/page.tsx')

assert.ok(api.includes("user.role!=='admin'"),'Only Administrations may read the report')
assert.ok(api.includes("'Cache-Control':'private, no-store'"),'Do not cache private records')
assert.ok(api.includes("query.includes('$1')?[days]:[]"),'Do not bind a date parameter to unparameterized SQL')
assert.ok(api.includes("status='sold' AND purchased_at"),'Only sold prospect packages are purchases')
assert.ok(api.includes("p.status='sold'"),'Bridger rankings must use sold packages')
assert.ok(api.includes("payment_status='paid' AND status='fulfilled'"),'Food fulfillment must be paid and completed')
assert.ok(api.includes("status='completed' AND payment_status='paid'"),'Cake fulfillment must be paid and completed')
assert.ok(api.includes("food_subtotal_ngn"),'Food revenue must exclude waybill charges')
assert.ok(api.includes("quoted_price_ngn"),'Cake revenue must exclude waybill charges')
assert.ok(api.includes("status='confirmed'"),'Modern File Folder count must use confirmed status')
assert.ok(api.includes("status='approved'"),'Legacy File Folder count must use approved status')
assert.ok(api.includes('ROW_NUMBER() OVER (PARTITION BY sale_key'), 'Deduplicate repeated File Numbers across purchase rails')
assert.ok(api.includes('available:false'), 'Missing or failed sources must be unavailable, never fabricated as zero')
assert.ok(api.includes("const foodQueue=await read"),'Open food exceptions must be separate from date-scoped sales')
assert.ok(api.includes("const cakeQueue=await read"),'Open cake exceptions must be separate from date-scoped sales')
assert.ok(ui.includes('/api/admin/company-movement?days='),'The page must load the authorized report')
assert.ok(ui.includes('setInterval(()=>void load(),20000)'),'Movement report must refresh at 20 seconds')
assert.ok(ui.includes('sec(table.key)?.available'),'Staff tables must reflect source availability')
assert.ok(entry.includes('href="/admin/company-movement"'),'Control Center must link to movement intelligence')
console.log('Administrations company movement contract: passed')
