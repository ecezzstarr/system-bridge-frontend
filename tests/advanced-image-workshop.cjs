const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const ts=require('typescript')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const house=read('app/(app)/image-workshop/page.tsx')
const archive=read('app/(app)/image-workshop/ai/page.tsx')
const route=read('app/api/image-workshop/route.ts')
const secure=read('app/api/image-workshop/assets/[id]/route.ts')
const config=read('lib/weave-image-workshop.ts')
const business=read('app/(app)/image-workshop/business/page.tsx')
const materials=read('app/(app)/image-workshop/branding/page.tsx')
const workflow=read('.github/workflows/production-check.yml')
for(const file of ['app/api/image-workshop/route.ts','app/(app)/image-workshop/ai/page.tsx','app/(app)/image-workshop/business/page.tsx','app/(app)/image-workshop/branding/page.tsx']){
  const source=ts.createSourceFile(file,read(file),ts.ScriptTarget.Latest,true,file.endsWith('.tsx')?ts.ScriptKind.TSX:ts.ScriptKind.TS)
  assert.deepEqual(source.parseDiagnostics,[],file+' has no syntax diagnostics')
}
assert(house.includes('data-weave-offline-image-business')&&house.includes('/api/image-workshop/samples'),'Original paid, no-API company Image House remains the default.')
assert(house.includes('/image-workshop/branding')&&house.includes('/image-workshop/business'),'Image House links physical product branding and business formation.')
assert(!house.includes('data-image-house-ai-extension'),'No provider-billed generation is advertised to participants.')
assert(config.includes('return false')&&!config.includes('OPENAI_API_KEY'),'Host credentials cannot accidentally enable paid image generation.')
assert(route.includes('export async function POST')&&route.includes('410'),'Previous generation endpoint fails closed.')
assert(!route.includes('api.openai.com')&&!route.includes('image/generations'),'Generation route makes no upstream provider requests.')
assert(archive.includes('data-weave-ai-gallery-readonly')&&!archive.includes("method:'POST'"),'Former gallery is read-only.')
assert(secure.includes('AND user_id=$2::uuid')&&secure.includes("getAuthUser(req)"),'Historical generated assets remain private and owner-scoped.')
assert(materials.includes('data-weave-material-branding')&&materials.includes('MATERIAL_MOCKUPS')&&materials.includes('artworkHash'),'Branding canvas supports real local customer artwork and separate licensed editions.')
assert(business.includes('data-branding-business-starter')&&business.includes('BRANDING_LAUNCH_STEPS'),'Starter roles have a guided business and advertising workflow.')
assert(workflow.includes('node tests/advanced-image-workshop.cjs'),'No-provider policy is enforced at CI.')
console.log('PASS: provider billing disabled, previous images readable, original paid House preserved, offline material editor and startup workflow available')
