const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const house=read('app/(app)/image-workshop/page.tsx')
const ai=read('app/(app)/image-workshop/ai/page.tsx')
const generation=read('app/api/image-workshop/route.ts')
const download=read('app/api/image-workshop/assets/[id]/route.ts')
const config=read('lib/weave-image-workshop.ts')
const workflow=read('.github/workflows/production-check.yml')
assert(house.includes('data-weave-offline-image-business'), 'Paid, no-API commercial Image House is preserved.')
assert(house.includes('/api/image-workshop/samples')&&house.includes('/image-workshop/ai'), 'Paid sample commerce remains primary with an optional AI entrance.')
assert(ai.includes('data-weave-advanced-image-workshop')&&ai.includes('Back to paid Image House'), 'AI creation is distinct from the existing business.')
assert(ai.includes("fetch('/api/image-workshop'")&&ai.includes("form.set('refineId'")&&ai.includes("form.append('references'"), 'Generation and edit requests use the existing API contract.')
assert(ai.includes('gpt-image-2.5-sunburst')&&ai.includes('gpt-image-2.5-flare'), 'AI model choices match the current server.')
assert(!ai.includes('gpt-image-2.6')&&!ai.includes("form.set('format'"), 'Client must not claim unsupported output formats or models.')
assert(config.includes("process.env.WEAVE_IMAGE_WORKSHOP_ENABLED === 'true'")&&config.includes("process.env.OPENAI_API_KEY"), 'Generation is default-off and requires funded server-side provider access.')
assert(generation.includes('imageWorkshopConfigured()')&&generation.includes('imageWorkshopDailyLimit()'), 'Backend verifies authorization and budget limits.')
assert(download.includes('AND user_id=$2::uuid')&&download.includes("getAuthUser(req)"), 'Saved image downloads enforce ownership.')
assert(download.includes("'Cache-Control':'private, no-store'"), 'Images are never cached as public files.')
assert(workflow.includes('node tests/advanced-image-workshop.cjs'), 'Optional AI production remains covered by CI.')
console.log('PASS: paid Image House preserved, optional provider-gated AI creation, private image downloads, existing API contract')
