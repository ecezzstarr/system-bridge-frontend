const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')

const catalog=read('lib/client-file-folder-world.ts')
const build=read('app/api/client/file-folder-world/route.ts')
const adminCatalog=read('app/api/admin/client-build-catalog/route.ts')
const permissions=read('lib/music-workshop.ts')
const api=read('app/api/music-workshop/route.ts')
const media=read('app/api/music-workshop/media/route.ts')
const publicMedia=read('app/api/media/[...path]/route.ts')
const engine=read('lib/music-loop-engine.ts')
const editor=read('components/music-workshop/music-conversation-editor.tsx')
const page=read('app/(app)/music-workshop/page.tsx')
const hosted=read('components/system-switch/client-file-folder-operating-environment.tsx')
const legion=read('app/(app)/weave/lifestyles/legion/page.tsx')
const layout=read('app/(app)/layout.tsx')

assert.ok(catalog.includes("'music_studio_kit'")&&catalog.includes("'music_studio'"),'Music Studio is Client-buildable')
assert.ok(catalog.includes("'music_studio_kit', 'Music Studio Kit'")&&catalog.includes("0, false]"),'Kit starts unpublished with no unapproved price')
assert.ok(build.includes("music_studio:{systems:[{systemType:'creator_booth'"),'Creator Booth required before Music Studio')
assert.ok(adminCatalog.includes("['music_studio_kit','animation_production_kit'].includes(key) && price <= 0"),'New creative kits cannot be published without a positive approved price')
assert.ok(adminCatalog.includes("['music_studio','animation_studio'].includes(key)"),'Creative blueprints cannot publish before their priced kits')
assert.ok(build.includes("'animation_studio','music_studio','streaming_gate'"),'One Music Studio structure per File Folder')
assert.ok(permissions.includes("system_type='music_studio' AND status='active'"),'Music production is blocked until Client build is active')
assert.ok(permissions.includes("l.active=true AND l.employment_status='active'"),'Only actively employed Legions inherit Client access')
assert.ok(permissions.includes('weave_music_collaborators'),'Invited staff are separately permission-scoped')
assert.ok(api.includes("if(!access.built)return fail("),'Music projects cannot be written before construction completes')
assert.ok(api.includes("if(!access.isOwner)return fail('Only the Client owner can invite"),'Only Client owner can invite other departments')
assert.ok(api.includes("WHERE id=$1::uuid AND client_id=$2::uuid AND file_number=$5"),'Project saves are owner-and-folder-scoped')
assert.ok(api.includes('owned.rows.length!==assetIds.length'),'Cross-Client sound references rejected')
assert.ok(media.includes('saveMediaObject(')&&media.includes("weave-private/music/"),'Real uploads saved privately in Weave media storage')
assert.ok(media.includes('Number(limits.files)>=60')&&media.includes('256*1024*1024'),'Music upload storage has a Client-level clip and byte limit')
assert.ok(media.includes("resolveMusicAccess(request,file)")&&media.includes("AND client_id=$2::uuid AND file_number=$3"),'Audio downloads authenticated to owner')
assert.ok(publicMedia.includes("objectName.startsWith('weave-private/music/')"),'Generic media route cannot leak private music files')
assert.ok(engine.includes('context.createOscillator()')&&engine.includes('context.createBufferSource()'),'Actual generated and uploaded audio production')
assert.ok(engine.includes('context.createStereoPanner()')&&engine.includes('track.level'),'Mixing supports real panning and levels')
assert.ok(engine.includes('context.currentTime')&&engine.includes('renderBeat(context'),'Tracks are scheduled on Web Audio time')
assert.ok(engine.includes('new OfflineAudioContext')&&engine.includes("chars('WAVE')"),'WAV export renders the mix, not mock data')
assert.ok(editor.includes('navigator.mediaDevices.getUserMedia')&&editor.includes('new MediaRecorder'),'Mic recording is real')
assert.ok(editor.includes('<SoundMeter analyser={analyser}')&&editor.includes('audioPeaks(buffer)'),'Waveforms and analyzer are based on decoded/live sound')
assert.ok(editor.includes('upload.wikimedia.org/wikipedia/commons/1/19/Mixing_desk_'),'Studio uses real documentary photo')
assert.ok(editor.includes('Hipposonic Studios')&&editor.includes('CC BY-SA 4.0'),'Real studio image is properly credited')
assert.ok(editor.includes('The words in motion')&&editor.includes('ENVIRONMENT answers'),'Word arrangement is explicitly conversational')
assert.ok(page.includes('data-weave-music-studio')&&page.includes('access.built'),'Studio page is in Weave but its production is construction-gated')
assert.ok(hosted.includes('href="/music-workshop"')&&hosted.includes("system.system_type==='music_studio'"),'Active File Folder system exposes the Music Studio entrance')
assert.ok(legion.includes('href="/music-workshop"'),'Hired Legion has private workshop entrance')
assert.ok(layout.includes("pathname !== '/music-workshop'"),'Exclusive Legion can enter Music Studio without reopening its general Agent/Bridger role')
console.log('Music Studio build, audio, visuals, access and privacy checks passed.')
