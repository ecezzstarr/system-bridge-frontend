const assert=require('node:assert/strict')
const fs=require('node:fs')
const vm=require('node:vm')
const path=require('node:path')
const ts=require('typescript')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const pure=read('lib/weave-open-world-domains.ts')
const transpiled=ts.transpileModule(pure,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText
const mod={exports:{}}
vm.runInNewContext(transpiled,{module:mod,exports:mod.exports,Math,Number,String},{filename:'weave-open-world-domains'})
const {worldLocationForSlot,projectPublicWorldDomain,verifyCastlePlacement}=mod.exports
const original=worldLocationForSlot(14)
const moved=projectPublicWorldDomain({id:'owned',slot:14,map_x:36,map_z:-42,open_door:false})
assert.equal(moved.location.slot,14,'Relocation does not replace permanent purchased slot')
assert.equal(moved.location.x,36)
assert.equal(moved.location.z,-42)
const unmoved=projectPublicWorldDomain({id:'legacy',slot:14,map_x:null,map_z:null})
assert.equal(unmoved.location.x,original.x)
assert.equal(unmoved.location.z,original.z)
assert.equal(verifyCastlePlacement(36,-42).ok,true,'Can choose vacant physical land')
assert.equal(verifyCastlePlacement(0,30).ok,false,'Protect live river ground')
assert.equal(verifyCastlePlacement(110,20).ok,false,'Out of world boundary is denied')
assert.equal(verifyCastlePlacement(16,-5).ok,false,'WEAVE Food Store stays clear')
assert.equal(verifyCastlePlacement(36,-42,[{x:40,z:-43}]).ok,false,'Prevent overlapping castles')
assert.equal(verifyCastlePlacement('not-a-position',20).ok,false)
const schema=read('lib/weave-open-world-store.ts')
const migration=read('migrations/20261024_weave_open_world_castle_positions.sql')
assert.ok(schema.includes('map_position_changed_at')&&schema.includes('map_x')&&schema.includes('map_z'))
assert.ok(schema.includes('map_x:row.map_x,map_z:row.map_z'),'Public positions use real verified saved coordinates')
assert.ok(migration.includes('weave_open_world_map_pair'),'DB coordinates are both set or both absent')
const route=read('app/api/client/open-world/castle-position/route.ts')
assert.ok(route.includes('getAuthUser(request)')&&route.includes("auth?.role==='client'"),'Logged-in Client status is verified server-side')
assert.ok(route.includes('resolveClientToken(bearer,sql)'),'Owned Client session token works')
assert.ok(route.includes("f.status='active'")&&route.includes("u.role='client'"),'Only active Client File Folders may relocate')
assert.ok(route.includes('validWriteOrigin(request)'),'Cross-site relocation requests are blocked')
assert.ok(route.includes("pg_advisory_xact_lock(hashtext('weave_open_world_castle_position'))"),'Concurrent castle claims are serialized')
assert.ok(route.includes('verifyCastlePlacement(proposed.point.x,proposed.point.z,occupied)'),'Server independently checks every other Client castle')
assert.ok(route.includes('SET map_x=$1,map_z=$2')&&!route.includes('SET world_slot='),'Castle placement never changes purchased slot')
const world=read('components/events/burning-river-live-world.tsx')
const land=read('components/world/weave-open-world-landscape.tsx')
const entry=read('app/system-switch/world/page.tsx')
assert.ok(world.includes('data-client-world-castle-relocation="owner-only"')&&world.includes('Position my castle'),'Verified Client has relocation control')
assert.ok(world.includes("'/api/client/open-world/castle-position'")&&world.includes('Confirm castle position'),'Castle moves only after affirmative confirmation')
assert.ok(land.includes('onPlace({x:event.point.x,z:event.point.z})'),'Tap real land to choose castle point')
assert.ok(world.includes("owner?.domainId===id")&&world.includes("window.location.assign('/client/system-switch')"),'Tapping own castle opens the private File Folder')
assert.ok(world.includes("if(href)window.location.assign(href)"),'Public visitor taps go only to real commissioned public market')
assert.ok(world.includes('publicHref(selectedDomain)'),'Selected Client products are reached through true Customer Door')
assert.ok(entry.includes('legionCode={legionCode}')&&world.includes("'&legion='+encodeURIComponent(legionCode)"),'Existing Legion attribution survives customer crossing')
const publicMarket=read('app/market/[slug]/page.tsx')
assert.ok(publicMarket.includes('client_store_items i')||publicMarket.includes('FROM client_store_items'),'Product list is read from actual Client public stock')
assert.ok(publicMarket.includes('teamSellers=await sql')&&publicMarket.includes('active=true AND sales_enabled=true'),'Only real active Team sales doors are offered')
assert.ok(publicMarket.includes('data-public-client-legion-storefronts="verified-active-sellers"'),'Visitor can choose Client team sellers without private world access')
assert.ok(publicMarket.includes('offers={offers}')&&publicMarket.includes('query.via===\'system-switch\''),'Public Customer Door retains real products and no redirect loop')
assert.ok(land.includes('<CityMaterial kind="paving"')&&land.includes('bumpMap={texture}'),'Existing real atlas path surfaces and textured physical terrain instead of wallpaper')
console.log('PASS: verified Client relocation, collisions, private entry, public products, Legion attribution and textured WEAVE land')
