const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')

const world=read('lib/client-file-folder-world.ts')
const build=read('app/api/client/file-folder-world/route.ts')
const api=read('app/api/animation-workshop/route.ts')
const access=read('lib/animation-workshop.ts')
const scene=read('components/animation-workshop/animation-movie-editor.tsx')
const client=read('components/system-switch/client-file-folder-operating-environment.tsx')
const legion=read('app/(app)/weave/lifestyles/legion/page.tsx')
const layout=read('app/(app)/layout.tsx')
assert.ok(world.includes("'animation_production_kit'")&&world.includes("'animation_studio'"),'Animation workshop is an actual purchase/build blueprint')
assert.ok(build.includes("animation_studio:{systems:[{systemType:'creator_booth'"),'Creator Booth must be built first')
assert.ok(build.includes("'broadcast_studio','animation_studio'"),'Only one build of each Animation Workshop is allowed')
assert.ok(access.includes("system_type='animation_studio' AND status='active'"),'Workshop opens only when the Client system is active')
assert.ok(access.includes("l.active=true AND l.employment_status='active'"),'Legion employment must still be active')
assert.ok(access.includes("weave_animation_collaborators"),'Other roles require a recorded invitation')
assert.ok(api.includes("if(!access.built)return reply("),'All project writes are construction-gated')
assert.ok(api.includes("if(!access.isOwner)return reply('Only the Client owner can invite staff.'"),'Only the owning Client grants access')
assert.ok(api.includes("WHERE id=$1::uuid AND client_id=$2::uuid"),'Project edits scoped to Client ownership')
assert.ok(scene.includes('new THREE.CanvasTexture')&&scene.includes('meshStandardMaterial'),'3D objects carry actual texture maps and physically based materials')
assert.ok(scene.includes('MediaRecorder')&&scene.includes('captureStream(24)'),'Rendered scene can be recorded as a film in the browser')
assert.ok(scene.includes("Movement keyframes")&&scene.includes("Start position"),'Actual timed motion is editable')
assert.ok(client.includes('href="/animation-workshop"'),'Live Client system has its studio door')
assert.ok(legion.includes('href="/animation-workshop"'),'Exclusive Legion workspace offers the workshop')
assert.ok(layout.includes("pathname !== '/animation-workshop'"),'Legion layout permits the Client workshop without reopening other position work')
console.log('Animation workshop static integration checks passed.')
