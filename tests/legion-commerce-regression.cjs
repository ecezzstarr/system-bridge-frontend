const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')

const commerce=read('lib/legion-commerce.ts')
const employment=read('lib/legion-employment.ts')
const enterpriseRoute=read('app/api/client/enterprise/route.ts')
const publicOrders=read('app/api/public/store/[slug]/orders/route.ts')
const publicMarket=read('app/market/[slug]/page.tsx')
const workshop=read('components/system-switch/enterprise-dream-panel.tsx')

assert.ok(commerce.includes('sales_code')&&commerce.includes('sales_enabled'),'Legions receive persistent sales Carrier identity')
assert.ok(commerce.includes('legion_id')&&commerce.includes('legion_sales_code')&&commerce.includes('legion_attributed_at'),'Customer Door orders persist Legion attribution')
assert.ok(employment.includes('legionCarrierPath')&&employment.includes("sales_code=COALESCE"),'Accepted Agent/Bridger Legions receive a Carrier into the Client market')
assert.ok(enterpriseRoute.includes('attributed_orders')&&enterpriseRoute.includes('paid_orders')&&enterpriseRoute.includes('attributed_revenue'),'Enterprise workshop loads Legion sales movement')
assert.ok(publicOrders.includes('client_id=${store.client_id}::uuid')&&publicOrders.includes('sales_enabled=true'),'Public order attribution only accepts an active Legion belonging to that Client')
assert.ok(publicOrders.includes('legion_id,legion_sales_code,legion_attributed_at'),'Customer Door order insertion records the carrying Legion')
assert.ok(publicMarket.includes('Legion Carrier:')&&publicMarket.includes('this Legion carried you here'),'Open-world Customer Door identifies the Legion without transferring Client ownership')
assert.ok(workshop.includes('Open Legion Carrier')&&workshop.includes('Client keeps ownership of the business and Customer Door'),'Enterprise Dream Workshop exposes Legion distribution while preserving Client ownership')

console.log('Recruited Client enterprise Legion commerce remains connected from employment to Carrier to attributed Customer Door order')
