const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const sale=read('lib/weave-flame-coin-sales.ts')
const publicApi=read('app/api/public/weave-flame-coin-sales/route.ts')
const adminApi=read('app/api/admin/weave-flame-coin-sales/route.ts')
const publicPage=read('app/system-switch/bridge-radiance/flame-coin/page.tsx')
const adminPage=read('app/(app)/admin/weave-flame-coin-sales/page.tsx')
const retired=read('app/api/public/weave-trx-sales/route.ts')
const retiredAdmin=read('app/api/admin/weave-trx-sales/route.ts')
const publicRedirect=read('app/system-switch/bridge-radiance/trx/page.tsx')
const adminRedirect=read('app/(app)/admin/weave-trx-sales/page.tsx')
const nav=read('lib/weave-role-districts.ts')
const plaza=read('components/system-switch/customer-door-avatar-world.tsx')
const gate=read('app/(app)/system-switch/flame-event/page.tsx')
const constants=read('lib/world/constants.ts')

assert.ok(!fs.existsSync(path.join(root,'lib/weave-trx-sales.ts')),'Obsolete sale-to-external-TRX engine must be absent')
assert.ok(constants.includes('TFT8e4EbMTvfQUGBHSz6LWTi4wokRBBz32'),'New Weave TRX funding address remains intact')
assert.ok(sale.includes('weave_flame_coin_orders'),'Flame Coin purchases use a distinct table')
assert.ok(sale.includes('flame_coin_amount'),'Order denomination is Flame Coin')
assert.ok(!sale.includes('destination_tron_wallet'),'No buyer TRON address required')
assert.ok(!sale.includes('delivery_tx_hash'),'No TRX transaction sent to buyers')
assert.ok(sale.includes("'payment_verified'")&&sale.includes('verification_evidence'),'Verify chosen payment independently before credit')
assert.ok(sale.includes("await db.query('BEGIN')")&&sale.includes('FOR UPDATE'),'Transfer must be atomic')
assert.ok(sale.includes("balance_trx=balance_trx-$1")&&sale.includes("balance_trx=balance_trx+$1"),'Value moves from funded Admin reserve to buyer wallet')
assert.ok(sale.includes('Math.round(value*1e8)'),'Amount must not exceed supported precision')
assert.ok(sale.includes("order.status==='credited'"),'Settlement must be idempotent')
assert.ok(sale.includes('credited_user_id'),'Buyer must receive internal Flame Coin')
assert.ok(sale.includes('buyer_email')&&sale.includes('recipient.email'),'Buyer identity must match registered account')
assert.ok(sale.includes('weave_receipts')&&sale.includes('ledger_entries'),'Payment must produce receipt and ledger')
assert.ok(sale.includes('flameCoinMethodEnabled'),'Each payment method requires independent approval')
assert.ok(sale.includes("['bank','card','trx','usdt','btc']"),'Prospects can choose all five payment methods')
assert.ok(sale.includes('WEAVE_USDT_TRC20_RECEIVING_ADDRESS')&&sale.includes('WEAVE_BTC_RECEIVING_ADDRESS'),'USDT and BTC must have separate configured receiving wallets')
assert.ok(sale.includes('WORLD_RULES.COMPANY_TRX_WALLET'),'TRX uses the company receiving wallet')
assert.ok(sale.includes('validFlameCoinProof'),'Crypto transaction hashes are validated distinctly from bank references')
assert.ok(publicApi.includes('amountFlameCoin')&&publicApi.includes('paymentMethod'),'Public order requests Flame Coin and preserves chosen payment rail')
assert.ok(publicApi.includes('validFlameCoinProof'),'Payment proof is method-specific')
assert.ok(!publicApi.includes('destinationTronWallet'),'Public order never asks for external crypto wallet')
assert.ok(publicPage.includes('Buy Flame Coin')&&publicPage.includes('Weave Main Wallet'),'Prospect UI names actual purchased value and destination')
for(const m of ['Bank transfer','Card','TRX','USDT','BTC'])assert.ok(publicPage.includes(m),m+' option is visible')
assert.ok(publicPage.includes('No raw card data')||publicPage.includes('no card details'),'Card details stay outside WEAVE')
assert.ok(!publicPage.includes('send TRX'),'Prospect UI must not promise crypto delivery')
assert.ok(adminApi.includes('creditVerifiedFlameCoinPurchase'),'Forensics settles into Main Wallet')
assert.ok(adminApi.includes('verify_payment')&&adminApi.includes('payment_network'),'Forensics verifies the method and network')
assert.ok(adminApi.includes('WEAVE_APPROVED_CARD_CHECKOUT_HOST'),'Card checkouts must be on approved hosted domain')
assert.ok(adminApi.includes("method==='card'&&body.finalCardSettlementConfirmed!==true"),'Card authorization alone cannot settle')
assert.ok(adminPage.includes('Credited')&&adminPage.includes('credit'),'Forensics UI credits buyers')
assert.ok(retired.includes('status:410')&&retiredAdmin.includes('status:410'),'Retired TRX-sales APIs cannot process orders')
assert.ok(publicRedirect.includes('/system-switch/bridge-radiance/flame-coin'),'Old prospect URL redirects')
assert.ok(adminRedirect.includes('/admin/weave-flame-coin-sales'),'Old Admin URL redirects')
for(const x of [nav,plaza,gate])assert.ok(x.includes('flame-coin'),'Navigation names Flame Coin rather than TRX sales')
console.log('Flame Coin prospect purchase, verified wallet transfer and legacy TRX-sale retirement checks passed')
