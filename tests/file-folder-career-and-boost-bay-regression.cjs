const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const ts=require('typescript')
const base=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(base,p),'utf8')
const workspace=read('components/system-switch/file-folder-open-world.tsx')
const client=read('components/system-switch/client-file-folder-operating-environment.tsx')
const blueprint=read('lib/file-folder-build-quote.ts')
const api=read('app/api/client/file-folder-world/route.ts')
const runtime=read('lib/file-folder-world-runtime.ts')
for(const file of ['components/system-switch/file-folder-open-world.tsx','components/system-switch/client-file-folder-operating-environment.tsx']){
 const s=ts.createSourceFile(file,read(file),ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX)
 assert.equal(s.parseDiagnostics.length,0,'Valid JSX for '+file)
}
assert(workspace.includes('data-file-folder-career-journey="choose-acquire-build-boost-operate-earn"'),'File Folder has a clear career-to-income path')
for(const title of ['Choose a career','Get materials','Build over time','Boost Bay','Operate your system','Earn from customers']){
 assert(workspace.includes(title),'Career step is named: '+title)
}
assert(workspace.includes('data-file-folder-career-service={blueprint.blueprint_key}'),'Actual blueprints have a customer-facing job explanation')
assert(workspace.includes('quoteFileFolderBlueprint(blueprint,owned)'),'Actual blueprint prices consider existing material inventory')
assert(workspace.includes('quote.priceAvailable')&&workspace.includes('quote.acquireCost.toLocaleString()'),'Unpublished prices are not invented')
assert(workspace.includes('effectiveMinutes')&&workspace.includes('blueprint.build_hours'),'Client is shown construction time from the real blueprint')
assert(workspace.includes('new Date(build.completes_at).toLocaleString()')&&workspace.includes('buildFormationProgress'),'Active builds use server-persisted timing and completion state')
assert(workspace.includes('data-file-folder-boost-target="active-construction"'),'Boost Bay selects a real active build')
assert(workspace.includes('setBoostTargetId(build.id)'),'Purchase invitation preserves the current build selection')
assert(workspace.includes("action:'purchase_item'")&&workspace.includes("action:'apply_build_item'"),'Boost purchase and installation use separate real API actions')
assert(workspace.includes('Number(inventory.get(item.item_key)||0)<1'),'Cannot install an unowned boost')
assert(workspace.includes("isBuildPartCompatible("),'Cannot install an incompatible part')
assert(workspace.includes('Install on selected build'),'After purchase the user can attach the boost to a build')
assert(api.includes("action === 'apply_build_item'")&&api.includes("action === 'purchase_item'"),'Backend verifies each action')
assert(api.includes('balance_trx >= ')&&api.includes('client_file_folder_item_orders'),'Company purchase is verified and recorded')
assert(api.includes("effectType === 'speed_boost'")&&api.includes('completes_at=CASE'),'Speed boost actually alters persisted completion time')
assert(api.includes('CLIENT_BUILD_SPEED_MAX'),'Boost has an enforced maximum')
assert(runtime.includes('export function buildFormationProgress')&&runtime.includes('completes_at'),'Displayed progress derives from persisted dates')
assert(blueprint.includes('materialMissing')&&blueprint.includes('purchaseAvailable'),'Acquisition quotes use actual owned and published materials')
assert(client.includes("label:'Acceleration Bay'"),'Existing Client navigation still reaches the same acceleration district')
assert(!workspace.includes('guaranteed customer earnings'),'No guaranteed earnings are introduced')
console.log('PASS: career-to-customer journey, actual prices, real-time builds, optional purchased boosts, owned installation and truthful income')
